    "xform/(.)ei$/$1W/",
    "xform/uan$/R/",
    "xform/[uv]e$/T/",
    "xform/un$/Y/",
    "xform/^sh/U/",
    "xform/^ch/I/",
    "xform/^zh/V/",
    "xform/uo$/O/",
    "xform/ie$/P/",
    "xform/i?ong$/S/",
    "xform/(ing|uai)$/K/",
    "xform/(.)ai$/$1D/",
    "xform/(.)en$/$1F/",
    "xform/(.)eng$/$1G/",
    "xform/[iu]ang$/L/",
    "xform/(.)ang$/$1H/",
