#!/usr/bin/env python3
"""Install the Cangjie customizations into Rime user directories.

Two independent parts, both for the stock `cangjie5` schema of rime-cangjie:

1. Segmentor: copies lua/delimited_code.lua and enables it in
   <schema>.custom.yaml, so that "vmpi;dl" looks up "vmpi" and "dl" as whole
   codes instead of letting the sentence maker re-split the input.

2. Dictionary: writes a copy of the shared <dictionary>.dict.yaml into the
   user directory in which the primary character of every duplicate code
   ranks first. The stock dictionary lists a secondary duplicate under both
   its "x" code and the plain code (欠 no / 久 no / 久 xno) and sorts by
   character frequency, so a more frequent secondary (久) hides the primary
   (欠) under both codes. The copy gives such a primary an explicit weight
   just above its competitors; nothing else is changed.

The user-directory copy shadows the shared dictionary, so rerun this script
after the rime-cangjie package is updated. Redeploy Rime afterwards.
"""

import argparse
import os
import shutil
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent
MARKER = "# generated by rime-german-gloss"
DICT_MARKER = MARKER + " install-cangjie.py"
SEGMENTOR_LINE = "engine/segmentors/@before 2: lua_segmentor@*delimited_code"
DEFAULT_COLUMNS = ["text", "code", "weight", "stem"]


def split_dict(text):
    """Split a .dict.yaml into (header lines, body lines) around the '...' line."""
    lines = text.split("\n")
    for i, line in enumerate(lines):
        if line.strip() == "...":
            return lines[: i + 1], lines[i + 1 :]
    raise ValueError("no '...' line: not a Rime dictionary")


def header_columns(header):
    """Return (columns, index of the last column line or None when defaulted)."""
    for i, line in enumerate(header):
        if line.strip() == "columns:":
            columns, last = [], None
            for j in range(i + 1, len(header)):
                item = header[j].strip()
                if not item.startswith("- "):
                    break
                columns.append(item[2:].strip())
                last = j
            if columns:
                return columns, last
    return list(DEFAULT_COLUMNS), None


def header_value(header, key, default):
    for line in header:
        if line.startswith(key + ":"):
            return line.split(":", 1)[1].strip().strip("\"'") or default
    return default


def load_essay(path):
    """Read a preset vocabulary (essay.txt) into {text: weight}."""
    weights = {}
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            text, sep, weight = line.rstrip("\n").partition("\t")
            if sep and weight.isdigit():
                weights[text] = int(weight)
    return weights


def reweight(text, essay):
    """Rank the primary character of each duplicate code first.

    Returns (new dictionary text, [(code, primary, new weight, displaced)]).
    A code is touched only when a character listed under it also has the code
    "x" + code, the first character listed does not, and frequency sorting
    would put another single character ahead of that first one. librime ranks
    single characters before phrases of the same code, so only the single
    characters compete.
    """
    header, body = split_dict(text)
    columns, last_column = header_columns(header)
    if "text" not in columns or "code" not in columns:
        raise ValueError("dictionary has no text/code columns")
    i_text, i_code = columns.index("text"), columns.index("code")
    add_weight_column = "weight" not in columns
    if add_weight_column:
        columns = columns + ["weight"]
    i_weight = columns.index("weight")

    def weight_of(fields):
        if i_weight < len(fields) and fields[i_weight].isdigit():
            return int(fields[i_weight])
        return essay.get(fields[i_text], 0)

    by_code = {}  # code -> [(line index, fields)] for single characters, in file order
    for n, line in enumerate(body):
        if not line or line.startswith("#"):
            continue
        fields = line.split("\t")
        if len(fields) <= max(i_text, i_code) or len(fields[i_text]) != 1:
            continue
        by_code.setdefault(fields[i_code], []).append((n, fields))

    changes = []
    for code, entries in by_code.items():
        secondary = {fields[i_text] for _, fields in by_code.get("x" + code, [])}
        n, primary = entries[0]
        listed = {fields[i_text] for _, fields in entries}
        if not (secondary & listed) or primary[i_text] in secondary:
            continue
        rivals = [f for _, f in entries[1:] if f[i_text] != primary[i_text]]
        top = max(rivals, key=weight_of)
        if weight_of(primary) >= weight_of(top):
            continue  # librime keeps file order between equal weights
        new_weight = weight_of(top) + 1
        fields = primary + [""] * (i_weight + 1 - len(primary))
        fields[i_weight] = str(new_weight)
        body[n] = "\t".join(fields)
        changes.append((code, primary[i_text], new_weight, top[i_text]))

    if add_weight_column and changes:
        if last_column is None:
            raise ValueError("cannot add a weight column to a dictionary without 'columns:'")
        indent = header[last_column][: len(header[last_column]) - len(header[last_column].lstrip())]
        header.insert(last_column + 1, indent + "- weight")
    return "\n".join(header + body), changes


# ---- installation ----------------------------------------------------------

def user_dirs():
    if os.name == "nt":
        dirs = []
        try:
            import winreg
            with winreg.OpenKey(winreg.HKEY_CURRENT_USER, r"Software\Rime\Weasel") as key:
                dirs.append(Path(os.path.expandvars(winreg.QueryValueEx(key, "RimeUserDir")[0])))
        except OSError:
            pass
        return dirs or [Path(os.environ.get("APPDATA", "")) / "Rime"]
    home = Path.home()
    data = Path(os.environ.get("XDG_DATA_HOME") or home / ".local/share")
    config = Path(os.environ.get("XDG_CONFIG_HOME") or home / ".config")
    return [
        data / "fcitx5/rime",
        home / ".var/app/org.fcitx.Fcitx5/data/fcitx5/rime",
        config / "ibus/rime",
        config / "fcitx/rime",
    ]


def shared_dirs():
    if os.name == "nt":
        dirs = []
        try:
            import winreg
            for sub in (r"SOFTWARE\Rime\Weasel", r"SOFTWARE\WOW6432Node\Rime\Weasel"):
                try:
                    with winreg.OpenKey(winreg.HKEY_LOCAL_MACHINE, sub) as key:
                        dirs.append(Path(winreg.QueryValueEx(key, "WeaselRoot")[0]) / "data")
                except OSError:
                    pass
        except ImportError:
            pass
        return dirs
    return [Path("/usr/share/rime-data"), Path("/usr/local/share/rime-data")]


def find_file(name, dirs):
    for d in dirs:
        if (d / name).is_file():
            return d / name
    return None


def enable_segmentor(user_dir, schema):
    custom = user_dir / (schema + ".custom.yaml")
    if not custom.exists():
        custom.write_text(MARKER + "\npatch:\n  " + SEGMENTOR_LINE + "\n", encoding="utf-8", newline="\n")
        print("    created %s" % custom.name)
        return
    text = custom.read_text(encoding="utf-8")
    if "delimited_code" in text:
        print("    %s already references delimited_code; unchanged" % custom.name)
    elif text.startswith(MARKER):
        custom.write_text(text.rstrip("\n") + "\n  " + SEGMENTOR_LINE + "\n", encoding="utf-8", newline="\n")
        print("    added delimited_code to %s" % custom.name)
    else:
        print("    %s exists and was NOT modified. Add under its 'patch:' key:" % custom.name)
        print("      " + SEGMENTOR_LINE)


def install_dict(user_dir, name, generated, force):
    target = user_dir / (name + ".dict.yaml")
    if target.exists() and not force:
        with open(target, encoding="utf-8") as fh:
            if not fh.readline().startswith(DICT_MARKER):
                print("    %s exists and was not generated by this script; kept (use --force)" % target.name)
                return
    target.write_text(generated, encoding="utf-8", newline="\n")
    print("    installed %s" % target.name)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--dir", action="append", type=Path, metavar="DIR",
                        help="Rime user directory (repeatable); default: every detected one")
    parser.add_argument("--schema", action="append", metavar="ID",
                        help="schema to enable the segmentor for (repeatable); default: cangjie5")
    parser.add_argument("--dictionary", default="cangjie5", metavar="NAME",
                        help="dictionary to fix (default: cangjie5)")
    parser.add_argument("--source", type=Path, metavar="FILE",
                        help="pristine NAME.dict.yaml; default: the one in the shared data directory")
    parser.add_argument("--essay", type=Path, metavar="FILE",
                        help="preset vocabulary; default: next to the source dictionary")
    parser.add_argument("--skip-segmentor", action="store_true", help="do not install the segmentor")
    parser.add_argument("--skip-dict", action="store_true", help="do not install the dictionary")
    parser.add_argument("--force", action="store_true",
                        help="overwrite a user-directory dictionary this script did not generate")
    args = parser.parse_args(argv)

    dirs = args.dir or [d for d in user_dirs() if d.is_dir()]
    if not dirs:
        sys.exit("No Rime user directory found. Deploy Rime once, or pass --dir DIR.")
    missing = [d for d in dirs if not d.is_dir()]
    if missing:
        sys.exit("Not a directory: %s" % missing[0])

    generated = None
    if not args.skip_dict:
        source = args.source or find_file(args.dictionary + ".dict.yaml", shared_dirs())
        if not source:
            sys.exit("%s.dict.yaml not found in the shared data directory; pass --source FILE." % args.dictionary)
        text = source.read_text(encoding="utf-8")
        if text.startswith(DICT_MARKER):
            sys.exit("%s was generated by this script; pass the pristine dictionary as --source." % source)
        header, _ = split_dict(text)
        vocabulary = header_value(header, "vocabulary", "essay") + ".txt"
        essay_path = args.essay or find_file(vocabulary, [source.parent] + shared_dirs())
        if not essay_path:
            sys.exit("%s not found; pass --essay FILE." % vocabulary)
        fixed, changes = reweight(text, load_essay(essay_path))
        generated = "%s from %s\n%s" % (DICT_MARKER, source, fixed)
        print("%s: %d duplicate codes now list their primary character first" % (source, len(changes)))

    for d in dirs:
        print("==> %s" % d)
        if not args.skip_segmentor:
            (d / "lua").mkdir(exist_ok=True)
            shutil.copyfile(REPO / "lua" / "delimited_code.lua", d / "lua" / "delimited_code.lua")
            print("    installed lua/delimited_code.lua")
            for schema in args.schema or ["cangjie5"]:
                enable_segmentor(d, schema)
        if generated is not None:
            install_dict(d, args.dictionary, generated, args.force)

    print("\nNow redeploy Rime (the dictionary is recompiled, which takes a moment).")


if __name__ == "__main__":
    main()
