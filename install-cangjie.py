#!/usr/bin/env python3
"""Install the Cangjie customizations into Rime user directories.

Three independent parts, all for the stock `cangjie5` schema of rime-cangjie:

1. Segmentor: copies lua/delimited_code.lua and enables it in
   <schema>.custom.yaml, so that "vmpi;dl" looks up "vmpi" and "dl" as whole
   codes instead of letting the sentence maker re-split the input.

2. Dictionary: writes a copy of the shared <dictionary>.dict.yaml into the
   user directory in which the primary character of every duplicate code
   ranks first. The stock dictionary lists a secondary duplicate under both
   its "x" code and the plain code (欠 no / 久 no / 久 xno) and sorts by
   character frequency, so a more frequent secondary (久) hides the primary
   (欠) under both codes. The copy gives such a primary an explicit weight
   just above its competitors; nothing else is changed.

3. Reverse lookup: the schema looks characters up by full Pinyin after a
   "`" prefix. This part makes it take 小鶴雙拼 instead and leaves the typed
   codes as they are in the preedit ("`ulpb" stays "ulpb", it is not expanded
   to "shuangpin"). It installs cangjie_flypy.schema.yaml, a helper schema
   that only compiles a Flypy prism for the luna_pinyin dictionary, and points
   the schema's reverse_lookup at it in <schema>.custom.yaml.

The user-directory copy shadows the shared dictionary, so rerun this script
after the rime-cangjie package is updated. Redeploy Rime afterwards.
"""

import argparse
import os
import shutil
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent
MARKER = "# generated by rime-german-gloss"
DICT_MARKER = MARKER + " install-cangjie.py"
SEGMENTOR_LINE = "engine/segmentors/@before 2: lua_segmentor@*delimited_code"
FLYPY = "cangjie_flypy"
# `preedit_format: []` must stay: without it the schema's own Pinyin rules
# apply to the codes and turn "nv" into "nü".
LOOKUP_LINES = [
    "schema/dependencies/@next: " + FLYPY,
    "reverse_lookup/dictionary: luna_pinyin",
    "reverse_lookup/prism: " + FLYPY,
    "reverse_lookup/tips: 〔雙拼〕",
    "reverse_lookup/preedit_format: []",
]
# 小鶴雙拼 spelling algebra of rime-double-pinyin's double_pinyin_flypy
# (install-jyutping.py carries the same list for its own helper schema).
