"""Unit tests for install-german.py.  Run:  python3 tests/test_install_german.py"""

import contextlib
import importlib.util
import io
import tempfile
import unittest
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
spec = importlib.util.spec_from_file_location("install_german", REPO / "install-german.py")
ig = importlib.util.module_from_spec(spec)
spec.loader.exec_module(ig)


TSV = "# generated by rime-german-gloss tools/build_dewiktionary.py\nHaus\t房子\n"


def run(*argv):
    out = io.StringIO()
    with contextlib.redirect_stdout(out):
        ig.main(list(argv))
    return out.getvalue()


class InstallTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        root = Path(self.tmp.name)
        self.user = root / "user"
        self.user.mkdir()
        self.built = root / "built"
        self.built.mkdir()
        (self.built / "deutsch.dict.yaml").write_text(
            "# generated by rime-german-gloss tools/build_dewiktionary.py\n---\nname: deutsch\n...\n",
            encoding="utf-8")
        (self.built / "de_zh.tsv").write_text(TSV, encoding="utf-8")

    def tearDown(self):
        self.tmp.cleanup()

    def install(self, *extra):
        return run("--dir", str(self.user), "--built", str(self.built), *extra)

    def test_installs_everything(self):
        out = self.install()
        schema = (self.user / "deutsch.schema.yaml").read_text(encoding="utf-8")
        self.assertTrue(schema.startswith(ig.SCHEMA_MARKER + "\n"))
        self.assertIn("schema_id: deutsch", schema)
        self.assertTrue((self.user / "deutsch.dict.yaml").is_file())
        self.assertEqual((self.user / "german_input" / "de_zh.tsv").read_text(encoding="utf-8"), TSV)
        for name in ig.LUA:
            self.assertTrue((self.user / "lua" / name).is_file(), name)
        self.assertIn("- schema: deutsch", out)
        self.assertTrue((self.user / ig.USER_TSV).read_text(encoding="utf-8").startswith("#"))

    def test_user_glosses_are_kept(self):
        (self.user / "german_input").mkdir()
        (self.user / ig.USER_TSV).write_text("Haus\t我的\n", encoding="utf-8")
        self.install("--force")
        self.assertEqual((self.user / ig.USER_TSV).read_text(encoding="utf-8"), "Haus\t我的\n")

    def test_schema_list_hint_only_when_missing(self):
        (self.user / "default.custom.yaml").write_text(
            "patch:\n  schema_list:\n    - schema: deutsch\n", encoding="utf-8")
        self.assertNotIn("- schema: deutsch", self.install())

    def test_reinstall_overwrites_own_files(self):
        self.install()
        (self.built / "de_zh.tsv").write_text("# generated by rime-german-gloss\nHaus\t家\n", encoding="utf-8")
        self.install()
        self.assertIn("家", (self.user / "german_input" / "de_zh.tsv").read_text(encoding="utf-8"))

    def test_foreign_files_are_kept(self):
        (self.user / "deutsch.schema.yaml").write_text("# my own\n", encoding="utf-8")
        out = self.install()
        self.assertIn("kept", out)
        self.assertEqual((self.user / "deutsch.schema.yaml").read_text(encoding="utf-8"), "# my own\n")
        self.install("--force")
        self.assertIn("schema_id: deutsch", (self.user / "deutsch.schema.yaml").read_text(encoding="utf-8"))

    def test_missing_build_output(self):
        (self.built / "de_zh.tsv").unlink()
        with self.assertRaises(SystemExit) as cm:
            self.install()
        self.assertIn("build_dewiktionary.py", str(cm.exception.code))


if __name__ == "__main__":
    unittest.main()
