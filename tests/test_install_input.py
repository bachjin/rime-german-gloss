"""Unit tests for install-input.py.  Run:  python3 tests/test_install_input.py"""

import contextlib
import importlib.util
import io
import tempfile
import unittest
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
spec = importlib.util.spec_from_file_location("install_input", REPO / "install-input.py")
ii = importlib.util.module_from_spec(spec)
spec.loader.exec_module(ii)


TSV = "# generated by rime-german-gloss tools/build_dewiktionary.py\nHaus\t房子\n"
FR_TSV = "# generated by rime-german-gloss tools/build_frwiktionary.py\nmaison\tn.f. · 房子\n"
JA_TSV = "# Generated by tools/build_ja_zh.py\n# sorted\n家\t名 · 房子\n"


def run(*argv):
    out = io.StringIO()
    with contextlib.redirect_stdout(out):
        ii.main(list(argv))
    return out.getvalue()


class InstallTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        root = Path(self.tmp.name)
        self.user = root / "user"
        self.user.mkdir()
        self.built = root / "built"
        for d in ("german_input", "french_input", "japanese_input"):
            (self.built / d).mkdir(parents=True)
        (self.built / "german_input" / "deutsch.dict.yaml").write_text(
            "# generated by rime-german-gloss tools/build_dewiktionary.py\n---\nname: deutsch\n...\n",
            encoding="utf-8")
        (self.built / "german_input" / "de_zh.tsv").write_text(TSV, encoding="utf-8")
        (self.built / "french_input" / "francais.dict.yaml").write_text(
            "# generated by rime-german-gloss tools/build_frwiktionary.py\n---\nname: francais\n...\n",
            encoding="utf-8")
        (self.built / "french_input" / "fr_zh.tsv").write_text(FR_TSV, encoding="utf-8")
        (self.built / "japanese_input" / "ja_zh.tsv").write_text(JA_TSV, encoding="utf-8")

    def tearDown(self):
        self.tmp.cleanup()

    def install(self, *extra, language="de"):
        return run("--dir", str(self.user), "--built", str(self.built), "--language", language, *extra)

    def test_installs_everything(self):
        out = self.install()
        schema = (self.user / "deutsch.schema.yaml").read_text(encoding="utf-8")
        self.assertTrue(schema.startswith(ii.SCHEMA_MARKER + "\n"))
        self.assertIn("schema_id: deutsch", schema)
        self.assertTrue((self.user / "deutsch.dict.yaml").is_file())
        self.assertEqual((self.user / "german_input" / "de_zh.tsv").read_text(encoding="utf-8"), TSV)
        for name in ii.KEYS_LUA:
            self.assertTrue((self.user / "lua" / name).is_file(), name)
        self.assertIn("- schema: deutsch", out)
        self.assertTrue((self.user / "german_input" / "de_zh.user.tsv").read_text(
            encoding="utf-8").startswith("#"))
        self.assertFalse((self.user / "francais.schema.yaml").exists())

    def test_french(self):
        out = self.install(language="fr")
        schema = (self.user / "francais.schema.yaml").read_text(encoding="utf-8")
        self.assertIn("schema_id: francais", schema)
        self.assertTrue((self.user / "francais.dict.yaml").is_file())
        self.assertEqual((self.user / "french_input" / "fr_zh.tsv").read_text(encoding="utf-8"), FR_TSV)
        self.assertIn("maison", (self.user / "french_input" / "fr_zh.user.tsv").read_text(encoding="utf-8"))
        self.assertIn("- schema: francais", out)

    def test_japanese_creates_patch(self):
        (self.user / "japanese.schema.yaml").write_text("schema:\n  schema_id: japanese\n", encoding="utf-8")
        out = self.install(language="ja")
        self.assertEqual((self.user / "japanese_input" / "ja_zh.tsv").read_text(encoding="utf-8"), JA_TSV)
        self.assertTrue((self.user / "lua" / "german_gloss.lua").is_file())
        self.assertTrue((self.user / "lua" / "japanese_kana.lua").is_file())
        self.assertFalse((self.user / "lua" / "german_keys.lua").exists())
        custom = (self.user / "japanese.custom.yaml").read_text(encoding="utf-8")
        self.assertTrue(custom.startswith(ii.MARKER))
        for line in ii.patch_lines(ii.LANGUAGES["ja"]):
            self.assertIn("  " + line + "\n", custom)
        self.assertNotIn("not in", out)
        self.assertIn("unchanged", self.install(language="ja"))

    def test_japanese_without_schema_warns(self):
        self.assertIn("install that schema too", self.install(language="ja"))

    def test_japanese_foreign_patch_is_kept(self):
        (self.user / "japanese.custom.yaml").write_text("patch:\n  menu/page_size: 5\n", encoding="utf-8")
        out = self.install(language="ja")
        self.assertIn("NOT modified", out)
        self.assertIn("lua_filter@*german_gloss@ja_zh", out)
        self.assertEqual((self.user / "japanese.custom.yaml").read_text(encoding="utf-8"),
                         "patch:\n  menu/page_size: 5\n")

    def test_japanese_generated_patch_is_updated(self):
        (self.user / "japanese.custom.yaml").write_text(
            ii.MARKER + "\npatch:\n  menu/page_size: 5\n  ja_zh/dictionary: old.tsv\n", encoding="utf-8")
        self.install(language="ja")
        custom = (self.user / "japanese.custom.yaml").read_text(encoding="utf-8")
        self.assertIn("menu/page_size: 5", custom)
        self.assertNotIn("old.tsv", custom)
        self.assertIn("ja_zh/base_dictionary: japanese_input/ja_zh.tsv", custom)

    def test_all_languages_by_default(self):
        run("--dir", str(self.user), "--built", str(self.built))
        for name in ("deutsch.schema.yaml", "francais.schema.yaml", "japanese.custom.yaml"):
            self.assertTrue((self.user / name).is_file(), name)

    def test_user_glosses_are_kept(self):
        (self.user / "german_input").mkdir()
        (self.user / "german_input" / "de_zh.user.tsv").write_text("Haus\t我的\n", encoding="utf-8")
        self.install("--force")
        self.assertEqual((self.user / "german_input" / "de_zh.user.tsv").read_text(encoding="utf-8"),
                         "Haus\t我的\n")

    def test_schema_list_hint_only_when_missing(self):
        (self.user / "default.custom.yaml").write_text(
            "patch:\n  schema_list:\n    - schema: deutsch\n", encoding="utf-8")
        self.assertNotIn("- schema: deutsch", self.install())

    def test_reinstall_overwrites_own_files(self):
        self.install()
        (self.built / "german_input" / "de_zh.tsv").write_text(
            "# generated by rime-german-gloss\nHaus\t家\n", encoding="utf-8")
        self.install()
        self.assertIn("家", (self.user / "german_input" / "de_zh.tsv").read_text(encoding="utf-8"))

    def test_foreign_files_are_kept(self):
        (self.user / "deutsch.schema.yaml").write_text("# my own\n", encoding="utf-8")
        out = self.install()
        self.assertIn("kept", out)
        self.assertEqual((self.user / "deutsch.schema.yaml").read_text(encoding="utf-8"), "# my own\n")
        self.install("--force")
        self.assertIn("schema_id: deutsch", (self.user / "deutsch.schema.yaml").read_text(encoding="utf-8"))

    def test_missing_build_output(self):
        (self.built / "french_input" / "fr_zh.tsv").unlink()
        with self.assertRaises(SystemExit) as cm:
            self.install(language="de,fr")
        self.assertIn("build_frwiktionary.py", str(cm.exception.code))
        self.assertFalse((self.user / "deutsch.schema.yaml").exists())

    def test_unknown_language(self):
        with self.assertRaises(SystemExit) as cm:
            self.install(language="es")
        self.assertIn("es", str(cm.exception.code))


if __name__ == "__main__":
    unittest.main()
