# ---- directories -----------------------------------------------------------

def user_dirs():
    if os.name == "nt":
        dirs = []
        try:
            import winreg
            with winreg.OpenKey(winreg.HKEY_CURRENT_USER, r"Software\Rime\Weasel") as key:
                dirs.append(Path(os.path.expandvars(winreg.QueryValueEx(key, "RimeUserDir")[0])))
        except OSError:
            pass
        return dirs or [Path(os.environ.get("APPDATA", "")) / "Rime"]
    home = Path.home()
    data = Path(os.environ.get("XDG_DATA_HOME") or home / ".local/share")
    config = Path(os.environ.get("XDG_CONFIG_HOME") or home / ".config")
    return [
        data / "fcitx5/rime",
        home / ".var/app/org.fcitx.Fcitx5/data/fcitx5/rime",
        config / "ibus/rime",
        config / "fcitx/rime",
    ]


def shared_dirs():
    if os.name == "nt":
        dirs = []
        try:
            import winreg
            for sub in (r"SOFTWARE\Rime\Weasel", r"SOFTWARE\WOW6432Node\Rime\Weasel"):
                try:
                    with winreg.OpenKey(winreg.HKEY_LOCAL_MACHINE, sub) as key:
                        dirs.append(Path(winreg.QueryValueEx(key, "WeaselRoot")[0]) / "data")
                except OSError:
                    pass
        except ImportError:
            pass
        return dirs
    return [Path("/usr/share/rime-data"), Path("/usr/local/share/rime-data")]


# ---- patches ---------------------------------------------------------------

def patch_lines(languages):
    """The <schema>.custom.yaml patch for `languages`; the first is the default."""
    options = [lang.option for lang in languages] + [NONE_OPTION]
    states = [lang.state for lang in languages] + [NONE_STATE]
    lines = [
        "switches/@next: {options: [%s], states: [%s]}" % (", ".join(options), ", ".join(states)),
        "engine/filters/+: [%s]" % ", ".join(lang.filter for lang in languages),
    ]
    for lang in languages:
        lines.append("%s/option: %s" % (lang.name_space, lang.option))
        if lang.name_space != "german_gloss":  # the filter's defaults are German
            lines.append("%s/dictionary: %s/%s" % (lang.name_space, lang.dir, lang.user_tsv))
            lines.append("%s/base_dictionary: %s/%s" % (lang.name_space, lang.dir, lang.base_tsv))
    return lines


def save_options_line(languages):
    options = [lang.option for lang in languages] + [NONE_OPTION]
    return "switcher/save_options/+: [%s]" % ", ".join(options)


def enable(user_dir, schema, lines):
    """Add `lines` to the patch of <schema>.custom.yaml. A file this repository
    generated is updated (dropping the filter line of older versions); someone
    else's file is left alone and the lines are printed instead."""
    custom = user_dir / (schema + ".custom.yaml")
    block = "".join("  %s\n" % line for line in lines)
    if not custom.exists():
        custom.write_text(MARKER + "\npatch:\n" + block, encoding="utf-8", newline="\n")
        print("    created %s" % custom.name)
        return
    text = custom.read_text(encoding="utf-8")
    if NONE_OPTION in text:
        print("    %s already sets up the glosses; unchanged" % custom.name)
    elif text.startswith(MARKER):
        kept = [line for line in text.splitlines() if line.strip() != OLD_FILTER_LINE]
        custom.write_text("\n".join(kept).rstrip("\n") + "\n" + block, encoding="utf-8", newline="\n")
        print("    added the gloss switch to %s" % custom.name)
    else:
        print("    %s exists and was NOT modified. Add under its 'patch:' key:" % custom.name)
        for line in lines:
            print("      " + line)
        if OLD_FILTER_LINE in text:
            print("    and remove its line '%s'" % OLD_FILTER_LINE)


# ---- files -----------------------------------------------------------------

def install_files(user_dir, languages, force):
    (user_dir / "lua").mkdir(exist_ok=True)
    shutil.copyfile(REPO / "lua" / "german_gloss.lua", user_dir / "lua" / "german_gloss.lua")
    print("    installed lua/german_gloss.lua")
    for lang in languages:
        (user_dir / lang.dir).mkdir(exist_ok=True)
        source = REPO / lang.dir / lang.user_tsv
        target = user_dir / lang.dir / lang.user_tsv
        name = "%s/%s" % (lang.dir, lang.user_tsv)
        if target.exists() and target.read_bytes() != source.read_bytes() and not force:
            shutil.copyfile(source, target.with_name(lang.user_tsv + ".new"))
            print("    kept %s (modified); new copy at %s.new (use --force to overwrite)" % (name, name))
        else:
            shutil.copyfile(source, target)
            print("    installed %s" % name)
        base = REPO / lang.dir / lang.base_tsv
        if base.is_file():
            shutil.copyfile(base, user_dir / lang.dir / lang.base_tsv)
            print("    installed %s/%s" % (lang.dir, lang.base_tsv))
        else:
            print("    no %s/%s (run tools/%s for the full dictionary)" % (lang.dir, lang.base_tsv, lang.tool))


# ---- schema list -----------------------------------------------------------

def schema_file(schema, dirs):
    for d in dirs:
        if (d / (schema + ".schema.yaml")).is_file():
            return d / (schema + ".schema.yaml")
    return None


def schema_name(path):
    """The schema/name of a schema file, read without a YAML parser."""
    with open(path, encoding="utf-8", errors="replace") as fh:
        for line in fh:
            m = re.match(r"^\s+name:\s*(.+?)\s*$", line)
            if m:
                return m.group(1).strip("\"'")
    return None


def enabled_schemas(user_dir, shared):
    """IDs in the schema_list: of default.custom.yaml if it sets one, else of default.yaml."""
    for path in [user_dir / "default.custom.yaml", user_dir / "default.yaml"] + \
            [d / "default.yaml" for d in shared]:
        if not path.is_file():
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        m = re.search(r"schema_list\s*:\s*\n((?:[ \t]*(?:-.*|#.*)?\n?)*)", text)
        if m:
            return re.findall(r"schema:\s*([\w.-]+)", m.group(1))
    return []


def list_schemas(user_dir):
    shared = shared_dirs()
    dirs = [user_dir] + shared
    enabled = enabled_schemas(user_dir, shared)
    print("    Official Rime schemas for Chinese ([installed] / [enabled] in schema_list):")
    for schema, fallback in OFFICIAL:
        path = schema_file(schema, dirs)
        marks = ("[installed]" if path else "") + ("[enabled]" if schema in enabled else "")
        name = (path and schema_name(path)) or fallback
        print("      %-22s %-20s %s" % (schema, marks, name))
    others = [s for s in enabled if s not in dict(OFFICIAL)]
    if others:
        print("    Other enabled schemas: %s" % ", ".join(others))
    print("    Enable the glosses for some of them with --schema ID,ID")


# ---- main ------------------------------------------------------------------

def deploy():
    for d in shared_dirs():
        deployer = d.parent / "WeaselDeployer.exe"
        if deployer.is_file():
            print("Running %s /deploy" % deployer)
            subprocess.run([str(deployer), "/deploy"], check=False)
            return
    print("WeaselDeployer.exe not found; redeploy Rime from its menu.")


def split_ids(values):
    return [v.strip() for value in values or [] for v in value.split(",") if v.strip()]


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--dir", action="append", type=Path, metavar="DIR",
                        help="Rime user directory (repeatable); default: every detected one")
    parser.add_argument("--language", action="append", metavar="CODE",
                        help="gloss languages, comma-separated: de, fr (default: de,fr); "
                             "the first is shown until another is picked")
    parser.add_argument("--schema", action="append", metavar="ID",
                        help="schemas to enable the glosses for (repeatable or comma-separated); "
                             "without it the official schemas are listed")
    parser.add_argument("--force", action="store_true",
                        help="overwrite your modified zh_de.tsv / zh_fr.tsv")
    parser.add_argument("--deploy", action="store_true",
                        help="run WeaselDeployer.exe /deploy afterwards (Windows)")
    args = parser.parse_args(argv)

    codes = split_ids(args.language) or ["de", "fr"]
    unknown = [c for c in codes if c not in LANGUAGES]
    if unknown:
        sys.exit("Unknown language %s; choose from %s." % (unknown[0], ", ".join(LANGUAGES)))
    languages = [LANGUAGES[c] for c in dict.fromkeys(codes)]
    schemas = split_ids(args.schema)

    dirs = args.dir or [d for d in user_dirs() if d.is_dir()]
    if not dirs:
        sys.exit("No Rime user directory found. Deploy Rime once, or pass --dir DIR.")
    missing = [d for d in dirs if not d.is_dir()]
    if missing:
        sys.exit("Not a directory: %s" % missing[0])

    for d in dirs:
        print("==> %s" % d)
        install_files(d, languages, args.force)
        if schemas:
            for schema in schemas:
                enable(d, schema, patch_lines(languages))
            enable(d, "default", [save_options_line(languages)])
        else:
            list_schemas(d)

    print()
    if args.deploy:
        deploy()
    else:
        print("Now redeploy Rime.")


if __name__ == "__main__":
    main()
