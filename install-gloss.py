#!/usr/bin/env python3
"""Install German and French glosses for Chinese schemas into Rime user directories.

Candidates of the schemas given with --schema get the German or French
translation of their text in the comment; a radio switch in the Ctrl+` menu
(德译 / 法译 / 无译) picks the language. Installs:

  lua/german_gloss.lua           the gloss filter (one instance per language)
  german_gloss/zh_de.tsv         your own German glosses (kept when modified)
  german_gloss/handedict.tsv     generated by tools/build_handedict.py, if present
  french_gloss/zh_fr.tsv         your own French glosses (kept when modified)
  french_gloss/cfdict.tsv        generated by tools/build_cfdict.py, if present

and patches <schema>.custom.yaml for each --schema, and default.custom.yaml so
that the chosen language is remembered. Without --schema it lists the official
Rime schemas for Chinese, marking the installed and enabled ones.
"""
import argparse
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent
MARKER = "# generated by rime-german-gloss"
NONE_OPTION = "gloss_none"
NONE_STATE = "无译"
OLD_FILTER_LINE = "engine/filters/@next: lua_filter@*german_gloss"


class Language:
    def __init__(self, code, name_space, state, user_tsv, base_tsv, tool):
        self.code = code
        self.name_space = name_space
        self.option = "gloss_" + code
        self.state = state
        self.dir = name_space
        self.user_tsv = user_tsv
        self.base_tsv = base_tsv
        self.tool = tool

    @property
    def filter(self):
        if self.name_space == "german_gloss":
            return "lua_filter@*german_gloss"
        return "lua_filter@*german_gloss@" + self.name_space


LANGUAGES = {
    "de": Language("de", "german_gloss", "德译", "zh_de.tsv", "handedict.tsv", "build_handedict.py"),
    "fr": Language("fr", "french_gloss", "法译", "zh_fr.tsv", "cfdict.tsv", "build_cfdict.py"),
}

