-- german_gloss.lua
-- librime-lua filter: append an offline German gloss to candidate comments.
--
-- Usage in a schema (or <schema>.custom.yaml patch):
--   engine/filters/@next: lua_filter@*german_gloss
--
-- Optional schema config (key = name space of the filter, default "german_gloss"):
--   german_gloss:
--     dictionary: german_gloss/zh_de.tsv   # relative to user/shared data dir, or absolute
--     base_dictionary: german_gloss/handedict.tsv  # optional big dictionary, "none" disables
--     opencc_config: t2s.json              # "none" disables script normalization
--     max_length: 100                      # characters shown per gloss, 0 = unlimited
--
-- `dictionary` holds the user's own entries and overrides `base_dictionary`,
-- which is generated by tools/build_handedict.py and silently skipped if absent.
--
-- Script normalization: dictionary keys and candidate texts are both mapped
-- to Simplified Chinese with OpenCC (default t2s.json, the same file librime's
-- simplifier uses), so one dictionary serves Traditional and Simplified output.
-- Exact matches take precedence over normalized ones. Keys of `base_dictionary`
-- are not normalized at load time; it is expected to list both scripts.
--
-- Split input: when the input is cut into segments (e.g. by delimited_code.lua,
-- "vmpi;dl" gives 约 + 束), each segment only offers its own candidates, so
-- the word they form would never be looked up. For a candidate of a later
-- segment the filter therefore first tries the texts chosen in the segments
-- right before it plus the candidate (约束), longest first, and shows that
-- word's gloss as "约束: zügeln (V)"; otherwise the candidate's own gloss.
--
-- Dictionary format: UTF-8 TSV, one entry per line: <Chinese>\t<German>.
-- Empty lines and lines starting with '#' are ignored. Repeated keys are
-- joined with "; " in file order (exact duplicates are dropped).
-- A generated dictionary whose header comments include the line "# sorted"
-- promises unique keys in byte order and no comments after the header; it
-- is searched as one string instead of being parsed into a table.

local M = {}

local DEFAULT_DICT = "german_gloss/zh_de.tsv"
local DEFAULT_BASE_DICT = "german_gloss/handedict.tsv"
local DEFAULT_OPENCC = "t2s.json"
local DEFAULT_MAX_LENGTH = 100

-- Loaded dictionaries, shared by every session and schema of this Lua state.
local cache = {}

local function log_warn(msg)
  if log and log.warning then
    log.warning("[german_gloss] " .. msg)
  end
end

local function trim(s)
  if not s:find("^%s") and not s:find("%s$") then
    return s -- common case, keeps loading a large dictionary fast
  end
  return (s:gsub("^%s+", ""):gsub("%s+$", ""))
end

-- Parse TSV content from an open file handle into a table text -> gloss.
function M.parse(fh)
  local dict = {}
  local first = true
  for raw in fh:lines() do
    local line = raw -- loop variables are read-only in Lua 5.5
    if first then
      line = line:gsub("^\239\187\191", "") -- strip UTF-8 BOM
      first = false
    end
    if line:byte(-1) == 13 then
      line = line:sub(1, -2)                -- tolerate CRLF files
    end
    if line ~= "" and line:sub(1, 1) ~= "#" then
      local key, gloss = line:match("^([^\t]+)\t(.+)$")
      if key then
        key, gloss = trim(key), trim(gloss)
        if key ~= "" and gloss ~= "" then
          local old = dict[key]
          if old == nil then
            dict[key] = gloss
          elseif old ~= gloss
              and ("; " .. old .. "; "):find("; " .. gloss .. "; ", 1, true) == nil then
            dict[key] = old .. "; " .. gloss
          end
        end
      end
    end
  end
  return dict
end

local function is_absolute(path)
  return path:sub(1, 1) == "/" or path:match("^%a:[/\\]") ~= nil
      or path:sub(1, 2) == "\\\\"
end

local function resolve_path(rel)
  if is_absolute(rel) then
    return { rel }
  end
  local paths = {}
  if rime_api then
    if rime_api.get_user_data_dir then
      paths[#paths + 1] = rime_api.get_user_data_dir() .. "/" .. rel
    end
    if rime_api.get_shared_data_dir then
      paths[#paths + 1] = rime_api.get_shared_data_dir() .. "/" .. rel
    end
  end
  return paths
end

-- Byte-wise a < b; the `<` operator compares with strcoll, which depends on
-- the process locale.
local function less(a, b)
  local n = math.min(#a, #b)
  for i = 1, n do
    local x, y = a:byte(i), b:byte(i)
    if x ~= y then
      return x < y
    end
  end
  return #a < #b
end

-- Gloss of `key` in `text`, the content of a dictionary whose lines from
-- byte `first` on are sorted by key in byte order with unique keys; nil if
-- absent. A binary search over the string itself.
function M.search(text, first, key)
  local lo, hi = first, #text + 1
  while lo < hi do
    local p = math.floor((lo + hi) / 2)
    while p > lo and text:byte(p - 1) ~= 10 do
      p = p - 1 -- back to the start of the line around the middle
    end
    local stop = (text:find("\n", p, true) or #text + 1) - 1
    local tab = text:find("\t", p, true)
    if not tab or tab > stop then
      tab = stop + 1
    end
    local k = text:sub(p, tab - 1)
    if k == key then
      local gloss = text:sub(tab + 1, stop)
      if gloss:byte(-1) == 13 then
        gloss = gloss:sub(1, -2)
      end
      return gloss ~= "" and gloss or nil
    elseif less(k, key) then
      lo = stop + 2
    else
      hi = p
    end
  end
  return nil
end

-- A dictionary table backed by the sorted content `text`: lookups search
-- the string instead of a Lua table. Hundreds of thousands of table entries
-- slow down every keystroke, as the garbage collector keeps traversing them.
function M.sorted_dict(text)
  local first = 1
  while text:byte(first) == 35 do -- header comment lines ('#')
    first = (text:find("\n", first, true) or #text) + 1
  end
  return setmetatable({}, { __index = function(_, key)
    if type(key) ~= "string" or key == "" or key:find("[\t\n]") then
      return nil
    end
    return M.search(text, first, key)
  end })
end

-- Load dictionary `rel`; `optional` suppresses the warning when it is absent.
-- A file whose header has a line "# sorted" (as tools/*.py write it) is kept
-- as one string and searched; others are parsed into a table.
function M.load(rel, optional)
  for _, path in ipairs(resolve_path(rel)) do
    local fh = io.open(path, "rb")
    if fh then
      local text = fh:read("*a")
      fh:close()
      text = text:gsub("^\239\187\191", "")
      local pos = 1
      while text:byte(pos) == 35 do -- header comment lines ('#')
        local stop = text:find("\n", pos, true) or #text + 1
        if text:sub(pos, stop - 1):match("^# sorted%s*$") then
          return M.sorted_dict(text), path
        end
        pos = stop + 1
      end
      local lines = {}
      function lines:lines()
        return text:gmatch("([^\n]*)\n?")
      end
      return M.parse(lines), path
    end
  end
  if not optional then
    log_warn("dictionary not found: " .. rel)
  end
  return {}, nil
end

-- Forget cached dictionaries (they are otherwise kept until Rime is redeployed).
function M.clear_cache()
  cache = {}
end

-- Shorten `text` to at most `max` UTF-8 characters, marking the cut with "…".
function M.truncate(text, max)
  if max == nil or max <= 0 or #text <= max then
    return text
  end
  local count = 0
  for pos in text:gmatch("()[^\128-\191]") do
    count = count + 1
    if count > max then
      return (text:sub(1, pos - 1):gsub("[%s;,]+$", "")) .. "…"
    end
  end
  return text
end

-- Return the comment to show for a candidate with comment `old` and gloss `gloss`.
function M.merge_comment(old, gloss)
  if old == nil or old == "" then
    return " " .. gloss
  end
  return old .. " " .. gloss
end

-- Return a candidate carrying the merged comment. Setting cand.comment is a
-- silent no-op in librime-lua for Shadow/Uniquified candidates (e.g. produced
-- by simplifier or uniquifier), so fall back to wrapping in a ShadowCandidate.
function M.annotate(cand, gloss)
  local comment = M.merge_comment(cand.comment, gloss)
  cand.comment = comment
  if cand.comment == comment then
    return cand
  end
  return ShadowCandidate(cand, cand.type, cand.text, comment)
end

-- Return an OpenCC converter for `name`, or nil if unavailable
-- (librime-lua without Opencc support, or config file not found).
function M.make_converter(name)
  if name == nil or name == "" or name == "none" or Opencc == nil then
    return nil
  end
  local ok, conv = pcall(Opencc, name)
  if ok and conv then
    return conv
  end
  log_warn("OpenCC config unavailable, script normalization disabled: " .. name)
  return nil
end

-- Add normalized aliases for keys whose normalized form is not yet present.
function M.add_aliases(dict, conv)
  local aliases = {}
  for key, gloss in pairs(dict) do
    local norm = conv:convert(key)
    if norm ~= key and dict[norm] == nil and aliases[norm] == nil then
      aliases[norm] = gloss
    end
  end
  for key, gloss in pairs(aliases) do
    dict[key] = gloss
  end
end

-- Exact match first, then match on the normalized text.
function M.lookup(dict, conv, text)
  local gloss = dict[text]
  if gloss == nil and conv ~= nil then
    local norm = conv:convert(text)
    if norm ~= text then
      gloss = dict[norm]
    end
  end
  return gloss
end

function M.init(env)
  local ns = (env.name_space or ""):gsub("^%*", "")
  if ns == "" then ns = "german_gloss" end
  local rel = DEFAULT_DICT
  local base_rel = DEFAULT_BASE_DICT
  local opencc_config = DEFAULT_OPENCC
  env.gloss_max_length = DEFAULT_MAX_LENGTH
  local config = env.engine and env.engine.schema and env.engine.schema.config
  if config then
    local v = config:get_string(ns .. "/dictionary")
    if v and v ~= "" then rel = v end
    local b = config:get_string(ns .. "/base_dictionary")
    if b and b ~= "" then base_rel = b end
    local o = config:get_string(ns .. "/opencc_config")
    if o then opencc_config = o end
    local m = tonumber(config:get_string(ns .. "/max_length"))
    if m then env.gloss_max_length = m end
  end

  local key = rel .. "\n" .. base_rel .. "\n" .. opencc_config
  local entry = cache[key]
  if entry == nil then
    entry = { dict = M.load(rel), base = {} }
    if base_rel ~= "none" then
      entry.base = M.load(base_rel, true)
    end
    entry.conv = M.make_converter(opencc_config)
    if entry.conv then
      M.add_aliases(entry.dict, entry.conv)
    end
    cache[key] = entry
  end
  env.gloss_dict = entry.dict
  env.gloss_base = entry.base
  env.gloss_conv = entry.conv
end

-- Called by librime-lua with the segment about to be filtered. Remembers
-- where it starts, so that func can find the segments before it.
function M.tags_match(segment, env)
  local ok, start = pcall(function() return segment.start end)
  env.gloss_segment_start = ok and start or nil
  return true
end

local function segments_of(segmentation)
  local ok, list = pcall(function() return segmentation:get_segments() end)
  if ok and type(list) == "table" then
    return list
  end
  list = {}
  local i = 0
  while true do
    local got, seg = pcall(function() return segmentation:get_at(i) end)
    if not got or seg == nil then
      return list
    end
    list[#list + 1] = seg
    i = i + 1
  end
end

-- Texts chosen in the run of segments that ends where the current segment
-- starts, in input order; empty when the current segment is the first.
function M.preceding_texts(env)
  local start = env.gloss_segment_start
  if not start or start <= 0 then
    return {}
  end
  local ok, texts = pcall(function()
    local by_end = {}
    for _, seg in ipairs(segments_of(env.engine.context.composition:toSegmentation())) do
      by_end[seg._end] = seg
    end
    local found, pos = {}, start
    while pos > 0 and by_end[pos] do
      local seg = by_end[pos]
      local cand = seg:get_selected_candidate()
      if not cand or cand.text == "" or seg.start >= pos then
        break
      end
      table.insert(found, 1, cand.text)
      pos = seg.start
    end
    return found
  end)
  return ok and texts or {}
end

-- Gloss for `text` in the user's dictionary, else in the base dictionary.
local function find(env, text)
  local conv = env.gloss_conv
  return M.lookup(env.gloss_dict or {}, conv, text) or M.lookup(env.gloss_base or {}, conv, text)
end

-- The gloss to show for `cand`: of the word it completes with the texts in
-- `before` (longest first), else of the candidate itself, else nil.
function M.gloss_for(cand, before, env)
  for i = 1, #before do
    local word = table.concat(before, "", i) .. cand.text
    local gloss = find(env, word)
    if gloss then
      return word .. ": " .. M.truncate(gloss, env.gloss_max_length)
    end
  end
  local gloss = find(env, cand.text)
  return gloss and M.truncate(gloss, env.gloss_max_length)
end

function M.func(input, env)
  local before = M.preceding_texts(env)
  for cand in input:iter() do
    -- A failing lookup must never cost the user a candidate.
    local ok, annotated = pcall(function()
      local gloss = M.gloss_for(cand, before, env)
      return gloss and M.annotate(cand, gloss)
    end)
    yield(ok and annotated or cand)
  end
end

function M.fini(env)
  env.gloss_dict = nil
  env.gloss_base = nil
  env.gloss_conv = nil
end

return M
