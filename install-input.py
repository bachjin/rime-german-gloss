#!/usr/bin/env python3
"""Install the foreign-language input schemas with Chinese glosses into Rime user directories.

  de  deutsch    German: muede or mude for müde, strasse for Straße
  fr  francais   French: eleve for élève, coeur for cœur, j' then ai for j'ai
  ja  japanese   Chinese glosses for the existing Japanese schema (rime-japanese,
                 not part of this repository)

Each candidate shows its Chinese gloss in the comment. Installs, per language:

  <schema>.schema.yaml      from german_input/ or french_input/ (de, fr)
  <schema>.dict.yaml        generated by tools/build_dewiktionary.py or
                            tools/build_frwiktionary.py (de, fr)
  <dir>/<xx>_zh.tsv         the glosses, generated by those tools or by
                            tools/build_ja_zh.py (ja)
  <dir>/<xx>_zh.user.tsv    your own glosses; created empty, never overwritten
  lua/german_gloss.lua      the gloss filter (shared with the Chinese schemas)
  lua/german_keys.lua       Space adds a space after the word; capitals (de, fr)
  lua/german_case.lua       capitalizes the candidates after a capital (de, fr)
  lua/japanese_kana.lua     F6 / F7 / F8 commit the input as hiragana / katakana /
                            half-width katakana (ja)

For ja the filter and the F6–F8 processor are added to japanese.custom.yaml.
Run the build tools first.
Then add `- schema: deutsch` / `- schema: francais` to the schema_list in
default.custom.yaml and redeploy Rime.
"""
import argparse
import os
import shutil
import sys
from collections import namedtuple
from pathlib import Path

REPO = Path(__file__).resolve().parent
MARKER = "# generated by rime-german-gloss"
SCHEMA_MARKER = MARKER + " install-input.py"
KEYS_LUA = ["german_gloss.lua", "german_keys.lua", "german_case.lua"]
USER_TSV_TEXT = """# Your own %s -> Chinese glosses; they override %s.
# One entry per line: <word><TAB><gloss>, e.g.
# %s\t%s
"""

# own_schema: the schema file comes from this repository; otherwise the
# filter is patched into an existing schema.
Language = namedtuple("Language", "code schema name dir own_schema tool lua example")
LANGUAGES = {
    "de": Language("de", "deutsch", "German", "german_input", True,
                   "build_dewiktionary.py", KEYS_LUA, "Haus\tdas · 房子"),
    "fr": Language("fr", "francais", "French", "french_input", True,
                   "build_frwiktionary.py", KEYS_LUA, "maison\tn.f. · 房子"),
    "ja": Language("ja", "japanese", "Japanese", "japanese_input", False,
                   "build_ja_zh.py", ["german_gloss.lua", "japanese_kana.lua"], "家\t名 · 房子"),
}
DEFAULT_LANGUAGES = ["de", "fr", "ja"]


def tsv(lang):
    return "%s/%s_zh.tsv" % (lang.dir, lang.code)


def user_tsv(lang):
    return "%s/%s_zh.user.tsv" % (lang.dir, lang.code)


def built_files(lang):
    """The build outputs a language needs, relative to the build directory."""
    files = [tsv(lang)]
    if lang.own_schema:
        files.insert(0, "%s/%s.dict.yaml" % (lang.dir, lang.schema))
    return files


def patch_lines(lang):
    """The japanese.custom.yaml patch that adds the gloss filter and F6–F8."""
    ns = "%s_zh" % lang.code
    return [
        "engine/filters/+: [lua_filter@*german_gloss@%s]" % ns,
        "engine/processors/@before 0: lua_processor@*japanese_kana",
        "%s/dictionary: %s" % (ns, user_tsv(lang)),
        "%s/base_dictionary: %s" % (ns, tsv(lang)),
        "%s/opencc_config: none" % ns,
    ]


def user_dirs():
    if os.name == "nt":
        dirs = []
        try:
            import winreg
            with winreg.OpenKey(winreg.HKEY_CURRENT_USER, r"Software\Rime\Weasel") as key:
                dirs.append(Path(os.path.expandvars(winreg.QueryValueEx(key, "RimeUserDir")[0])))
        except OSError:
            pass
        return dirs or [Path(os.environ.get("APPDATA", "")) / "Rime"]
    home = Path.home()
    data = Path(os.environ.get("XDG_DATA_HOME") or home / ".local/share")
    config = Path(os.environ.get("XDG_CONFIG_HOME") or home / ".config")
    return [
        data / "fcitx5/rime",
        home / ".var/app/org.fcitx.Fcitx5/data/fcitx5/rime",
        config / "ibus/rime",
        config / "fcitx/rime",
    ]


def generated(path):
    """True when `path` is absent or was written by this repository's scripts."""
    if not path.exists():
        return True
    with open(path, encoding="utf-8", errors="replace") as fh:
        return fh.readline().startswith(MARKER)


def place(source, user_dir, name, force, header=""):
    """Copy `source` to <user_dir>/<name> unless that is someone else's file."""
    target = user_dir / name
    if not force and not generated(target):
        print("    %s exists and was not installed by this repository; kept (use --force)" % name)
        return
    target.parent.mkdir(parents=True, exist_ok=True)
    if header:
        target.write_text(header + source.read_text(encoding="utf-8"), encoding="utf-8", newline="\n")
    else:
        shutil.copyfile(source, target)
    print("    installed %s" % name)


def enable(user_dir, lang):
    """Add the gloss filter to <schema>.custom.yaml: create it, or update a
    file this repository generated; someone else's file is left alone and
    the lines are printed instead."""
    custom = user_dir / (lang.schema + ".custom.yaml")
    lines = patch_lines(lang)
    ns = "%s_zh/" % lang.code
    if not custom.exists():
        custom.write_text(MARKER + "\npatch:\n" + "".join("  %s\n" % l for l in lines),
                          encoding="utf-8", newline="\n")
        print("    created %s" % custom.name)
        return
    text = custom.read_text(encoding="utf-8")
    present = {line.strip() for line in text.splitlines()}
    if all(line in present for line in lines):
        print("    %s already adds the glosses; unchanged" % custom.name)
    elif text.startswith(MARKER):
        kept = [l for l in text.splitlines()
                if not (l.strip().startswith(ns) or l.strip() in lines)]
        custom.write_text("\n".join(kept).rstrip("\n") + "\n" + "".join("  %s\n" % l for l in lines),
                          encoding="utf-8", newline="\n")
        print("    added the glosses to %s" % custom.name)
    else:
        print("    %s exists and was NOT modified. Add under its 'patch:' key:" % custom.name)
        for line in lines:
            print("      " + line)


def install(user_dir, lang, built, force):
    if lang.own_schema:
        name = lang.schema + ".schema.yaml"
        place(REPO / lang.dir / name, user_dir, name, force, SCHEMA_MARKER + "\n")
        place(built / lang.dir / (lang.schema + ".dict.yaml"), user_dir, lang.schema + ".dict.yaml", force)
    place(built / tsv(lang), user_dir, tsv(lang), force)
    if not (user_dir / user_tsv(lang)).exists():
        example = lang.example.split("\t")
        (user_dir / user_tsv(lang)).write_text(
            USER_TSV_TEXT % (lang.name, tsv(lang).split("/")[1], example[0], example[1]),
            encoding="utf-8", newline="\n")
        print("    created %s" % user_tsv(lang))
    (user_dir / "lua").mkdir(exist_ok=True)
    for name in lang.lua:
        shutil.copyfile(REPO / "lua" / name, user_dir / "lua" / name)
        print("    installed lua/%s" % name)

    if not lang.own_schema:
        if not (user_dir / (lang.schema + ".schema.yaml")).is_file():
            print("    %s.schema.yaml is not in %s; install that schema too" % (lang.schema, user_dir))
        enable(user_dir, lang)
        return
    default = user_dir / "default.custom.yaml"
    if not (default.exists() and lang.schema in default.read_text(encoding="utf-8")):
        print("    %s is not enabled. Add to the schema_list in default.custom.yaml:" % lang.schema)
        print("      - schema: %s" % lang.schema)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--language", default=",".join(DEFAULT_LANGUAGES), metavar="LIST",
                        help="comma-separated, of %s (default: all)" % ", ".join(LANGUAGES))
    parser.add_argument("--dir", action="append", type=Path, metavar="DIR",
                        help="Rime user directory (repeatable); default: every detected one")
    parser.add_argument("--built", type=Path, default=REPO, metavar="DIR",
                        help="directory holding the build tools' output directories "
                             "german_input/ etc. (default: this repository)")
    parser.add_argument("--force", action="store_true",
                        help="overwrite user-directory files this repository did not install")
    args = parser.parse_args(argv)

    codes = [c.strip() for c in args.language.split(",") if c.strip()]
    unknown = [c for c in codes if c not in LANGUAGES]
    if unknown or not codes:
        sys.exit("Unknown language %r; choose from %s." % (unknown[0] if unknown else "",
                                                           ", ".join(LANGUAGES)))
    languages = [LANGUAGES[c] for c in codes]
    for lang in languages:
        absent = [n for n in built_files(lang) if not (args.built / n).is_file()]
        if absent:
            sys.exit("%s not found in %s. Run tools/%s first, or leave out --language %s."
                     % (absent[0], args.built, lang.tool, lang.code))
    dirs = args.dir or [d for d in user_dirs() if d.is_dir()]
    if not dirs:
        sys.exit("No Rime user directory found. Deploy Rime once, or pass --dir DIR.")
    missing = [d for d in dirs if not d.is_dir()]
    if missing:
        sys.exit("Not a directory: %s" % missing[0])

    for d in dirs:
        for lang in languages:
            print("==> %s (%s)" % (d, lang.schema))
            install(d, lang, args.built, args.force)
    print("\nNow redeploy Rime (the first deployment compiles dictionaries of about a"
          " million words, which takes a while).")


if __name__ == "__main__":
    main()
