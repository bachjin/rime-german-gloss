#!/usr/bin/env python3
"""Install the German input schema `deutsch` into Rime user directories.

Typing the ASCII spelling of a German word (muede or mude for müde, strasse
for Straße) offers the word with its Chinese gloss in the comment. Installs:

  deutsch.schema.yaml        from german_input/
  deutsch.dict.yaml          generated by tools/build_dewiktionary.py
  german_input/de_zh.tsv     generated by tools/build_dewiktionary.py
  german_input/de_zh.user.tsv  your own glosses; created empty, never overwritten
  lua/german_gloss.lua       the gloss filter (shared with the Chinese schemas)
  lua/german_keys.lua        Space adds a space after the word; capitals
  lua/german_case.lua        capitalizes the candidates after a capital

Run tools/build_dewiktionary.py first. Then add `- schema: deutsch` to the
schema_list in default.custom.yaml and redeploy Rime.
"""
import argparse
import os
import shutil
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent
MARKER = "# generated by rime-german-gloss"
SCHEMA_MARKER = MARKER + " install-german.py"
SCHEMA = "deutsch"
LUA = ["german_gloss.lua", "german_keys.lua", "german_case.lua"]
TSV = "german_input/de_zh.tsv"
USER_TSV = "german_input/de_zh.user.tsv"
USER_TSV_TEXT = """# Your own German -> Chinese glosses; they override de_zh.tsv.
# One entry per line: <German word><TAB><gloss>, e.g.
# Haus\tdas · 房子
"""


def user_dirs():
    if os.name == "nt":
        dirs = []
        try:
            import winreg
            with winreg.OpenKey(winreg.HKEY_CURRENT_USER, r"Software\Rime\Weasel") as key:
                dirs.append(Path(os.path.expandvars(winreg.QueryValueEx(key, "RimeUserDir")[0])))
        except OSError:
            pass
        return dirs or [Path(os.environ.get("APPDATA", "")) / "Rime"]
    home = Path.home()
    data = Path(os.environ.get("XDG_DATA_HOME") or home / ".local/share")
    config = Path(os.environ.get("XDG_CONFIG_HOME") or home / ".config")
    return [
        data / "fcitx5/rime",
        home / ".var/app/org.fcitx.Fcitx5/data/fcitx5/rime",
        config / "ibus/rime",
        config / "fcitx/rime",
    ]


def generated(path):
    """True when `path` is absent or was written by this repository's scripts."""
    if not path.exists():
        return True
    with open(path, encoding="utf-8", errors="replace") as fh:
        return fh.readline().startswith(MARKER)


def place(source, user_dir, name, force, header=""):
    """Copy `source` to <user_dir>/<name> unless that is someone else's file."""
    target = user_dir / name
    if not force and not generated(target):
        print("    %s exists and was not installed by this repository; kept (use --force)" % name)
        return
    target.parent.mkdir(parents=True, exist_ok=True)
    if header:
        target.write_text(header + source.read_text(encoding="utf-8"), encoding="utf-8", newline="\n")
    else:
        shutil.copyfile(source, target)
    print("    installed %s" % name)


def install(user_dir, built, force):
    place(REPO / "german_input" / (SCHEMA + ".schema.yaml"), user_dir, SCHEMA + ".schema.yaml",
          force, SCHEMA_MARKER + "\n")
    place(built / (SCHEMA + ".dict.yaml"), user_dir, SCHEMA + ".dict.yaml", force)
    place(built / "de_zh.tsv", user_dir, TSV, force)
    if not (user_dir / USER_TSV).exists():
        (user_dir / USER_TSV).write_text(USER_TSV_TEXT, encoding="utf-8", newline="\n")
        print("    created %s" % USER_TSV)
    (user_dir / "lua").mkdir(exist_ok=True)
    for name in LUA:
        shutil.copyfile(REPO / "lua" / name, user_dir / "lua" / name)
        print("    installed lua/%s" % name)

    default = user_dir / "default.custom.yaml"
    if not (default.exists() and SCHEMA in default.read_text(encoding="utf-8")):
        print("    %s is not enabled. Add to the schema_list in default.custom.yaml:" % SCHEMA)
        print("      - schema: %s" % SCHEMA)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--dir", action="append", type=Path, metavar="DIR",
                        help="Rime user directory (repeatable); default: every detected one")
    parser.add_argument("--built", type=Path, default=REPO / "german_input", metavar="DIR",
                        help="output directory of tools/build_dewiktionary.py (default: german_input/)")
    parser.add_argument("--force", action="store_true",
                        help="overwrite user-directory files this repository did not install")
    args = parser.parse_args(argv)

    absent = [n for n in (SCHEMA + ".dict.yaml", "de_zh.tsv") if not (args.built / n).is_file()]
    if absent:
        sys.exit("%s not found in %s. Run tools/build_dewiktionary.py first." % (absent[0], args.built))
    dirs = args.dir or [d for d in user_dirs() if d.is_dir()]
    if not dirs:
        sys.exit("No Rime user directory found. Deploy Rime once, or pass --dir DIR.")
    missing = [d for d in dirs if not d.is_dir()]
    if missing:
        sys.exit("Not a directory: %s" % missing[0])

    for d in dirs:
        print("==> %s" % d)
        install(d, args.built, args.force)
    print("\nNow redeploy Rime (the first deployment compiles a dictionary of about a"
          " million words, which takes a while).")


if __name__ == "__main__":
    main()
