#!/usr/bin/env python3
"""Build the dictionaries of the German input schema `deutsch`.

Usage: tools/build_dewiktionary.py [--source FILE] [--zh-source FILE]
           [--handedict FILE] [--frequency FILE] [--essay FILE]
           [--output-dir DIR] [--no-forms]

Writes two files into DIR (default: german_input/ of this repository):

  deutsch.dict.yaml  Rime table dictionary. The code of a word is its ASCII
                     spelling (müde -> muede, Straße -> strasse); a word with
                     umlauts is listed a second time under the plain vowels
                     (mude), slightly lower.
  de_zh.tsv          German word -> grammar and Chinese, read by
                     lua/german_gloss.lua:
                       Haus   das · 复数 Häuser · 房子、住房
                       gehen  动 不规则 · ging, ist gegangen · 走，步行; …
                       ging   gehen 的过去式 · 走，步行; …

Sources (each downloaded when not given; standard library only):
  --source     German Wiktionary extracted by wiktextract (kaikki.org): the
               word list, gender, plural, principal parts, the inflected
               forms and some Chinese translations.
  --zh-source  Chinese Wiktionary extracted the same way: Chinese glosses of
               about 90 000 German words, the first choice for the Chinese.
  --handedict  HanDeDict (handedict.u8), read backwards for the words neither
               Wiktionary has Chinese for.
  --frequency  FrequencyWords de_50k.txt ("word count" lines), for ranking.
  --essay      Rime's essay.txt (optional), ranks the Chinese of HanDeDict.
"""
import argparse
import gzip
import json
import os
import re
import shutil
import sys
import tempfile
import time
import unicodedata
import urllib.request

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import build_handedict  # noqa: E402

WIKTIONARY_URL = "https://kaikki.org/dewiktionary/raw-wiktextract-data.jsonl.gz"
ZH_WIKTIONARY_URL = "https://kaikki.org/zhwiktionary/raw-wiktextract-data.jsonl.gz"
FREQUENCY_URL = "https://raw.githubusercontent.com/hermitdave/FrequencyWords/master/content/2018/de/de_50k.txt"
REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MARKER = "# generated by rime-german-gloss tools/build_dewiktionary.py"
CHINESE = {"zh", "zh-cn", "cmn"}
MAX_GLOSSES = 4
MAX_SENSES = 3

FOLD = {"ä": "ae", "ö": "oe", "ü": "ue", "ß": "ss", "æ": "ae", "œ": "oe", "ø": "o"}
LOOSE = {"ä": "a", "ö": "o", "ü": "u"}
CODE = re.compile(r"^[a-z]+$")
HAN_CHARS = "㐀-鿿豈-﫿\U00020000-\U0003ffff"
HAN = re.compile("^[%s]+$" % HAN_CHARS)
HAS_HAN = re.compile("[%s]" % HAN_CHARS)
GERMAN_WORD = re.compile(r"^[A-Za-zÄÖÜäöüßéèêàâçñ]+$")
ARTICLE = re.compile(r"^(?:der|die|das|den|dem|des|ein|eine|einen|einem|einer|eines)\s+")
PARENS = re.compile(r"\([^()]*\)")
# Usage notes of the Chinese Wiktionary in ASCII brackets: "[接 與格 …]", "(習慣上…)".
NOTES = re.compile(r"\s*(?:\[[^\[\]]*\]|\([^()]*\))")
# A part-of-speech prefix some glosses start with: "v. 教导", "adj. 走路的".
POS_PREFIX = re.compile(r"^(?:adj|adv|v|n|vt|vi|prep|conj)\.\s*")
# Pronunciation sections parsed as senses: "* 国际音标^(): /ˈhaʊ̯zn̩/".
PRONUNCIATION = re.compile(r"国际音标|國際音標|/[^/]*[ˈˌː][^/]*/")

ARTICLES = {"masculine": "der", "feminine": "die", "neuter": "das"}
POS_LABELS = {"verb": "动", "adj": "形", "adv": "副", "prep": "介", "conj": "连",
              "pron": "代", "article": "冠", "num": "数", "intj": "叹", "particle": "小品"}
AUX = {"haben": "hat", "sein": "ist"}
CASES = {"nominative", "genitive", "dative", "accusative"}
FORM_LABELS = [("imperative", "命令式"), ("subjunctive-ii", "第二虚拟式"),
               ("subjunctive-i", "第一虚拟式"), ("subjunctive", "第一虚拟式"),
               ("past", "过去式"), ("present", "现在时"), ("comparative", "比较级"),
               ("superlative", "最高级"), ("plural", "复数")]


def fold(word, table=FOLD):
    """The code of `word`, or None when it is not made of letters only."""
    out = []
    for ch in word.lower():
        if ch in table:
            out.append(table[ch])
        elif ch in FOLD:
            out.append(FOLD[ch])
        else:
            out.append(unicodedata.normalize("NFD", ch)[0])
    code = "".join(out)
    return code if CODE.match(code) else None


def codes(word):
    """[(code, is_loose)]: the ASCII spelling, then the one with plain vowels."""
    code = fold(word)
    if code is None:
        return []
    result = [(code, False)]
    loose = fold(word, LOOSE)
    if loose and loose != code:
        result.append((loose, True))
    return result


# ---- grammar ---------------------------------------------------------------

def form_label(tags):
    """What an inflected form is, from the tags of its form-of sense."""
    t = set(tags) - {"form-of"}
    if "participle-2" in t or t == {"perfect"}:
        return "第二分词"
    if "participle" in t and "present" in t:
        return "第一分词"
    for tag, label in FORM_LABELS:
        if tag in t:
            return label
    return "变格" if t & CASES else "变形"


def split_separable(form):
    """("fing", "an") for "fing an"; (form, "") for one word."""
    head, _, prefix = form.partition(" ")
    return head, prefix


def is_regular(form, infinitive, endings):
    """Whether `form` is the stem of `infinitive` plus one of `endings`."""
    head, prefix = split_separable(form)
    if prefix and infinitive.startswith(prefix):
        infinitive = infinitive[len(prefix):]
    stem = infinitive[:-2] if infinitive.endswith("en") else infinitive[:-1]
    return any(head == stem + e for e in endings)


def first_form(forms, test):
    for f in forms:
        if test(set(f.get("tags", []))):
            return f.get("form", "")
    return ""


def verb_grammar(word, entry):
    """"动 不规则 · spricht, sprach, hat gesprochen", "动 · ist gereist" or "动".
    A verb is irregular when Wiktionary says so or its past is not stem + te."""
    forms = entry.get("forms", [])
    present = [f.get("form", "") for f in forms if f.get("tags") == ["present"]]
    third = present[2] if len(present) >= 3 else ""  # ich, du, er/sie/es
    past = first_form(forms, lambda t: t == {"past"})
    participle = first_form(forms, lambda t: "participle-2" in t)
    aux = [f.get("form") for f in forms
           if {"auxiliary", "perfect"} <= set(f.get("tags", [])) and f.get("form") in AUX]
    perfect = ""
    if participle:
        perfect = ("/".join(dict.fromkeys(AUX[a] for a in aux)) + " " + participle).strip()
    if not past:
        return "动"
    if "irregular" in entry.get("tags", []) or not is_regular(past, word, ("te", "ete")):
        parts = [past]
        if third and not is_regular(third, word, ("t", "et")):
            parts.insert(0, third)
        if perfect:
            parts.append(perfect)
        return "动 不规则 · " + ", ".join(parts)
    if "sein" in aux and perfect:
        return "动 · " + perfect
    return "动"


def noun_grammar(entry):
    """"das · 复数 Häuser", "der/das", "复数 Leute" ..."""
    tags = entry.get("tags", [])
    articles = [ARTICLES[t] for t in ("masculine", "feminine", "neuter") if t in tags]
    plural = first_form(entry.get("forms", []), lambda t: {"nominative", "plural"} <= t)
    parts = ["/".join(articles)] if articles else []
    if plural and plural not in ("—", "-"):
        parts.append("复数 " + plural)
    return " · ".join(parts)


def adj_grammar(word, entry):
    """"形 · besser, am besten" when the comparison is not just word + er."""
    forms = entry.get("forms", [])
    comparative = first_form(forms, lambda t: t == {"comparative"})
    superlative = first_form(forms, lambda t: t == {"superlative"})
    base = word[:-1] if word.endswith("e") else word
    if comparative and comparative != base + "er":
        return "形 · " + ", ".join(f for f in (comparative, superlative) if f)
    return "形"


def grammar_of(word, entry):
    pos = entry.get("pos")
    if pos == "noun":
        return noun_grammar(entry)
    if pos == "verb":
        return verb_grammar(word, entry)
    if pos == "adj":
        return adj_grammar(word, entry)
    return POS_LABELS.get(pos, "")


# ---- sources ---------------------------------------------------------------

def read_wiktionary(lines):
    """Return (translations, names, forms, lemmas, grammar) from wiktextract
    JSON lines: translations {word: [Chinese]} of common words, names the
    same for proper names (Essen the city), forms {form: [(lemma, label)]},
    lemmas {word that has an entry other than an inflected form}, grammar
    {lemma: "das · 复数 Häuser"} from its first entry that gives one."""
    translations, names, forms, lemmas, grammar = {}, {}, {}, set(), {}
    compared = {}  # besser -> {gut: 比较级}: its form-of sense has no tags
    for line in lines:
        entry = json.loads(line)
        if entry.get("lang_code") != "de":
            continue
        word = entry.get("word", "")
        if not GERMAN_WORD.match(word):
            continue
        if "form-of" not in entry.get("tags", []):
            lemmas.add(word)
            if not grammar.get(word):  # the first entry that has any
                grammar[word] = grammar_of(word, entry)
            for f in entry.get("forms", []):
                tags = set(f.get("tags", []))
                if tags in ({"comparative"}, {"superlative"}):
                    compared.setdefault(f.get("form", ""), {})[word] = form_label(tags)
        zh = [t["word"] for t in entry.get("translations", [])
              if t.get("lang_code") in CHINESE and HAN.match(t.get("word", ""))]
        if zh:
            table = names if entry.get("pos") == "name" else translations
            table.setdefault(word, []).extend(zh)
        for sense in entry.get("senses", []):
            for target in sense.get("form_of", []):
                lemma = target.get("word", "")
                if lemma and lemma != word:
                    forms.setdefault(word, []).append((lemma, form_label(sense.get("tags", []))))
    for form in forms:
        # One label per lemma, the first one (the main sense).
        labels = {}
        for lemma, label in forms[form]:
            if label == "变形":
                label = compared.get(form, {}).get(lemma, label)
            labels.setdefault(lemma, label)
        forms[form] = list(labels.items())
    for table in (translations, names):
        for key in table:
            table[key] = list(dict.fromkeys(table[key]))
    grammar = {w: g for w, g in grammar.items() if g}
    return translations, names, forms, lemmas, grammar


def clean_gloss(gloss):
    if PRONUNCIATION.search(gloss):
        return ""
    gloss = re.sub(r"\s*\n\s*", "; ", gloss)  # "流产\n②堕胎": numbered senses on new lines
    gloss = POS_PREFIX.sub("", NOTES.sub("", gloss).strip()).rstrip("。.;；")
    return gloss if HAS_HAN.search(gloss) else ""


def read_zh_wiktionary(lines):
    """{German word: [Chinese gloss of each sense]} from the Chinese Wiktionary."""
    glosses = {}
    for line in lines:
        entry = json.loads(line)
        if entry.get("lang_code") != "de":
            continue
        word = entry.get("word", "")
        if not GERMAN_WORD.match(word):
            continue
        for sense in entry.get("senses", []):
            if "form-of" in sense.get("tags", []):
                continue
            for gloss in sense.get("glosses", []):
                gloss = clean_gloss(gloss)
                if gloss:
                    glosses.setdefault(word, []).append(gloss)
    return {w: list(dict.fromkeys(g)) for w, g in glosses.items()}


def split_items(sense):
    """Split a HanDeDict sense at the commas and semicolons outside parentheses."""
    items, depth, cur = [], 0, []
    for ch in sense:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth = max(0, depth - 1)
        if depth == 0 and ch in ",;":
            items.append("".join(cur))
            cur = []
        else:
            cur.append(ch)
    items.append("".join(cur))
    return items


def german_word(item):
    """The single German word an item like "die Straße (S)" stands for, or None."""
    while PARENS.search(item):
        item = PARENS.sub("", item)
    item = ARTICLE.sub("", item.strip()).strip()
    return item if GERMAN_WORD.match(item) else None


def read_handedict(lines, essay=None):
    """Return ({German word: [Chinese]}, {Traditional char: Simplified char}).
    A Chinese headword ranks higher the more frequent it is in `essay` (keyed
    by Traditional text) and the earlier the word comes in its senses."""
    essay = essay or {}
    found, t2s, simplified = {}, {}, set()
    for trad, simp, senses in build_handedict.parse(lines):
        if len(trad) == 1 and len(simp) == 1:
            simplified.add(simp)
            if trad != simp:
                t2s.setdefault(trad, simp)
        if not HAN.match(simp):
            continue
        position = 0
        for sense in senses:
            if build_handedict.PROPER_NAME.search(sense):
                continue
            for item in split_items(sense):
                word = german_word(item)
                if word:
                    # 给 lists für fifth but is far more common than 适于, which lists it first.
                    rank = (-(essay.get(trad, 0) + 10) / (1 + position), len(simp))
                    best = found.setdefault(word, {})
                    if simp not in best or rank < best[simp]:
                        best[simp] = rank
                position += 1
    # A character that is also written in Simplified text keeps its form: 事
    # has its own entry, so a stray 事 -> 亊 pair must not turn 做事 into 做亊.
    t2s = {t: s for t, s in t2s.items() if t not in simplified}
    return {w: sorted(c, key=c.get) for w, c in found.items()}, t2s


def read_frequency(lines):
    freq = {}
    for line in lines:
        parts = line.split()
        if len(parts) == 2 and parts[1].isdigit():
            freq.setdefault(parts[0].lower(), int(parts[1]))
    return freq


def read_essay(lines):
    essay = {}
    for line in lines:
        parts = line.rstrip("\n").split("\t")
        if len(parts) == 2 and parts[1].isdigit():
            essay[parts[0]] = int(parts[1])
    return essay


# ---- build -----------------------------------------------------------------

def simplify(text, t2s):
    return "".join(t2s.get(ch, ch) for ch in text)


def chinese_of(word, translations, names, zh_glosses, handedict, t2s):
    """The Chinese for `word`: Chinese Wiktionary senses, else the single-word
    translations of German Wiktionary and HanDeDict; proper names last."""
    if word in zh_glosses:
        senses = [simplify(g, t2s) for g in zh_glosses[word][:MAX_SENSES]]
        extra = [simplify(t, t2s) for t in translations.get(word, [])]
        zh = senses + [t for t in extra if not any(t in g for g in senses)][:1]
    else:
        zh = [simplify(t, t2s) for t in translations.get(word, [])] + handedict.get(word, [])
        zh = list(dict.fromkeys(zh))[:MAX_GLOSSES]
    zh += [simplify(t, t2s) for t in names.get(word, [])]
    return list(dict.fromkeys(zh))


def build(translations, names, forms, lemmas, grammar, zh_glosses, handedict, t2s, freq,
          with_forms=True):
    """Return ({word: gloss}, [(word, code, weight)]). Inflected forms whose
    lemma has no Chinese are typeable but get no gloss: listing them would
    triple the table german_gloss.lua holds in memory."""
    chinese = {}
    for word in lemmas | forms.keys() | handedict.keys() | zh_glosses.keys():
        zh = chinese_of(word, translations, names, zh_glosses, handedict, t2s)
        if zh:
            chinese[word] = zh
    vocabulary = set(chinese) | lemmas
    if with_forms:
        vocabulary |= forms.keys()

    glosses = {}
    for word in vocabulary:
        if word in lemmas and (word in chinese or word in grammar):
            parts = [grammar.get(word, ""), "; ".join(chinese.get(word, []))]
            glosses[word] = " · ".join(p for p in parts if p)
            continue
        # An inflected form (Häuser, or Häusern, also a place without Chinese
        # of its own): what it is of which lemma, and the lemma's Chinese.
        pointers = []
        for lemma, label in forms.get(word, []):
            if lemma in chinese and len(pointers) < 2:
                pointers.append("%s 的%s · %s" % (lemma, label, chinese[lemma][0]))
        if pointers:
            glosses[word] = " / ".join(pointers)
        elif word in chinese:
            glosses[word] = "; ".join(chinese[word])

    entries = []
    for word in vocabulary:
        # Frequency first (it ignores case); then glossed lemmas before
        # forms, and the verb gehen before the noun Gehen.
        weight = freq.get(word.lower(), 0) * 10
        weight += 3 if word in chinese else (1 if word in lemmas else 0)
        weight += 1 if word in lemmas and word.islower() else 0
        for code, loose in codes(word):
            entries.append((word, code, weight * 9 // 10 if loose and weight > 9 else weight))
    entries.sort(key=lambda e: (e[1], -e[2], e[0]))
    return glosses, entries


DICT_HEADER = """%s
# Sources: German and Chinese Wiktionary via kaikki.org (CC BY-SA),
# HanDeDict (CC BY-SA 2.0), FrequencyWords by Hermit Dave (CC BY-SA 4.0).
---
name: deutsch
version: "%s"
sort: by_weight
columns:
  - text
  - code
  - weight
...
"""


def write_outputs(out_dir, glosses, entries, version):
    os.makedirs(out_dir, exist_ok=True)
    dict_path = os.path.join(out_dir, "deutsch.dict.yaml")
    with open(dict_path, "w", encoding="utf-8", newline="\n") as out:
        out.write(DICT_HEADER % (MARKER, version))
        for word, code, weight in entries:
            out.write("%s\t%s\t%d\n" % (word, code, weight))
    tsv_path = os.path.join(out_dir, "de_zh.tsv")
    with open(tsv_path, "w", encoding="utf-8", newline="\n") as out:
        out.write(MARKER + "\n")
        out.write("# German and Chinese Wiktionary via kaikki.org and HanDeDict - licensed CC BY-SA\n")
        out.write("# sorted\n")  # unique keys in byte order: german_gloss.lua searches the file
        for word in sorted(glosses):
            # A tab or line break in a gloss would break the sorted lines.
            out.write(word + "\t" + re.sub(r"[\t\r\n]+", " ", glosses[word]) + "\n")
    return dict_path, tsv_path


# ---- main ------------------------------------------------------------------

def open_lines(path):
    if path.endswith(".gz"):
        return gzip.open(path, "rt", encoding="utf-8")
    return open(path, encoding="utf-8")


def download(url, tmp_dir, name=None):
    path = os.path.join(tmp_dir, name or url.rsplit("/", 1)[1])
    print("downloading " + url, file=sys.stderr)
    with urllib.request.urlopen(url) as resp, open(path, "wb") as out:
        shutil.copyfileobj(resp, out)
    return path


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--source", help="German Wiktionary raw-wiktextract-data.jsonl[.gz]; default: download (~300 MB)")
    ap.add_argument("--zh-source", help="Chinese Wiktionary raw-wiktextract-data.jsonl[.gz]; default: download (~220 MB)")
    ap.add_argument("--handedict", help="handedict.u8; default: download")
    ap.add_argument("--frequency", help="de_50k.txt; default: download")
    ap.add_argument("--essay", help="Rime essay.txt, ranks the Chinese of HanDeDict")
    ap.add_argument("--output-dir", default=os.path.join(REPO, "german_input"))
    ap.add_argument("--no-forms", action="store_true",
                    help="leave out inflected forms that are not also a lemma")
    args = ap.parse_args(argv)

    with tempfile.TemporaryDirectory() as tmp:
        source = args.source or download(WIKTIONARY_URL, tmp, "de-wiktextract.jsonl.gz")
        zh_source = args.zh_source or download(ZH_WIKTIONARY_URL, tmp, "zh-wiktextract.jsonl.gz")
        handedict = args.handedict or download(build_handedict.URL, tmp)
        frequency = args.frequency or download(FREQUENCY_URL, tmp)

        essay = {}
        if args.essay:
            with open(args.essay, encoding="utf-8") as fh:
                essay = read_essay(fh)
        with open(handedict, encoding="utf-8") as fh:
            reverse, t2s = read_handedict(fh, essay)
        with open(frequency, encoding="utf-8") as fh:
            freq = read_frequency(fh)
        print("reading " + source, file=sys.stderr)
        with open_lines(source) as fh:
            translations, names, forms, lemmas, grammar = read_wiktionary(fh)
        print("reading " + zh_source, file=sys.stderr)
        with open_lines(zh_source) as fh:
            zh_glosses = read_zh_wiktionary(fh)

    glosses, entries = build(translations, names, forms, lemmas, grammar, zh_glosses,
                             reverse, t2s, freq, with_forms=not args.no_forms)
    version = time.strftime("%Y.%m.%d")
    dict_path, tsv_path = write_outputs(args.output_dir, glosses, entries, version)
    print("wrote %d codes to %s" % (len(entries), dict_path), file=sys.stderr)
    print("wrote %d glosses to %s" % (len(glosses), tsv_path), file=sys.stderr)


if __name__ == "__main__":
    main()
