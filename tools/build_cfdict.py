#!/usr/bin/env python3
"""Build french_gloss/cfdict.tsv from CFDICT (CC BY-SA 3.0).

Usage: tools/build_cfdict.py [--source FILE] [--output FILE]
  --source FILE  local cfdict.u8 (CEDICT format); default: download from chine.in
  --output FILE  default: french_gloss/cfdict.tsv next to this repository's lua/

Like tools/build_handedict.py: every entry is written under its Traditional and
its Simplified headword, proper names come last. Standard library only.
"""
import argparse
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import build_handedict  # noqa: E402

URL = "https://chine.in/assets/cfdict/cfdict.u8"
REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# Some CFDICT lines separate the fields with several spaces or a tab.
ENTRY = re.compile(r"^(\S+)\s+(\S+)\s+\[[^\]]*\]\s*/(.*)/\s*$")
IDIOM = re.compile(r"^\(expr\. idiom\.?\)\s*")
PROPER_NAME = re.compile(
    r"^\((?:nom de famille|nom de lieu|nom d'une? |xian de|utilisé dans les noms)")


def clean(sense):
    sense = IDIOM.sub("", " ".join(sense.split()))
    return sense.strip(" ;,")


def build(lines):
    """Return {headword: [senses]}: ordinary senses first, then measure-word
    senses ("(classificateur pour …)", often long), then proper names."""
    entries = build_handedict.build(lines, ENTRY, clean, PROPER_NAME)
    for senses in entries.values():
        senses.sort(key=lambda s: (PROPER_NAME.search(s) is not None,
                                   s.startswith("(classificateur")))
    return entries


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--source")
    ap.add_argument("--output", default=os.path.join(REPO, "french_gloss", "cfdict.tsv"))
    args = ap.parse_args()

    entries = build(build_handedict.read_source(args.source, URL).splitlines())
    build_handedict.write(entries, args.output, [
        "Generated by tools/build_cfdict.py from CFDICT",
        "https://chine.in/mandarin/dictionnaire/CFDICT/ - licensed CC BY-SA 3.0",
    ])
    print("wrote %d headwords to %s" % (len(entries), args.output), file=sys.stderr)


if __name__ == "__main__":
    main()
