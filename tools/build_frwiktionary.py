#!/usr/bin/env python3
"""Build the dictionaries of the French input schema `francais`.

Usage: tools/build_frwiktionary.py [--source FILE] [--zh-source FILE]
           [--cfdict FILE] [--frequency FILE] [--essay FILE]
           [--output-dir DIR] [--no-forms]

Writes two files into DIR (default: french_input/ of this repository):

  francais.dict.yaml  Rime table dictionary. The code of a word is its spelling
                      without accents (élève -> eleve, cœur -> coeur, peut-être
                      -> peutetre); the apostrophe stays (aujourd'hui), and is
                      also left out a second time, slightly lower (aujourdhui).
  fr_zh.tsv           French word -> grammar and Chinese, read by
                      lua/german_gloss.lua:
                        maison  n.f. · 房子，住宅
                        cheval  n.m. · 复数 chevaux · 马; 骑术
                        allais  aller 的未完成过去时 · 去，走

Sources (each downloaded when not given; standard library only):
  --source     French Wiktionary extracted by wiktextract (kaikki.org): the
               word list, gender, plural, feminine, the inflected forms and
               some Chinese translations.
  --zh-source  Chinese Wiktionary extracted the same way: Chinese glosses of
               about 30 000 French words, the first choice for the Chinese.
  --cfdict     CFDICT (cfdict.u8), read backwards for the words neither
               Wiktionary has Chinese for.
  --frequency  FrequencyWords fr_50k.txt ("word count" lines), for ranking.
  --essay      Rime's essay.txt (optional), ranks the Chinese of CFDICT.
"""
import argparse
import json
import os
import re
import sys
import tempfile
import time
import unicodedata

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import build_cfdict  # noqa: E402
import build_dewiktionary  # noqa: E402
import build_handedict  # noqa: E402

WIKTIONARY_URL = "https://kaikki.org/frwiktionary/raw-wiktextract-data.jsonl.gz"
FREQUENCY_URL = "https://raw.githubusercontent.com/hermitdave/FrequencyWords/master/content/2018/fr/fr_50k.txt"
REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MARKER = "# generated by rime-german-gloss tools/build_frwiktionary.py"
CHINESE = build_dewiktionary.CHINESE
HAN = build_dewiktionary.HAN
HAS_HAN = build_dewiktionary.HAS_HAN
MAX_GLOSSES = 4
MAX_SENSES = 3

FOLD = {"œ": "oe", "æ": "ae", "ß": "ss"}
CODE = re.compile(r"^[a-z]+(?:'[a-z]+)*'?$")
# Letters, inner hyphens and apostrophes; a final apostrophe for j', qu'.
FRENCH_WORD = re.compile(r"^[A-Za-zÀ-ÖØ-öø-ÿŒœÆæ]+(?:[-'][A-Za-zÀ-ÖØ-öø-ÿŒœÆæ]+)*'?$")
# Parts of speech the Chinese Wiktionary writes into its glosses, as in a
# printed dictionary: "n.m. 马；骑术", "女低音；中提琴adj. 中音的".
ABBREVIATION = r"(?:n|v|adj|adv|a|vt|vi|prép|prep|conj|pron|interj|loc|art)(?:\.[a-z]{1,4})*\."
POS_MARKS = re.compile(r"\s*%s(?:\s*(?:et|ou)\s*%s)*\s*" % (ABBREVIATION, ABBREVIATION))
PLURAL_NOTE = re.compile(r"\s*pl\.\s.*$")
# "Élision de la conjonction que devant une voyelle": its form_of names the
# part of speech (conjonction), not the word, which comes before "devant".
ELISION = re.compile(r"^Élision\b.*?(\w+)(?: (?:et|ou) \w+)? devant")

POS_LABELS = {"verb": "v.", "adj": "adj.", "adv": "adv.", "prep": "prép.", "conj": "conj.",
              "pron": "pron.", "article": "art.", "det": "dét.", "num": "num.",
              "intj": "interj.", "onomatopoeia": "onomat."}
GENDERS = {"masculine": "n.m.", "feminine": "n.f."}
# What an inflected form is, from the French gloss of its form-of sense
# ("Première personne du singulier de l'indicatif imparfait du verbe aller."):
# the first pattern found wins.
FORM_LABELS = [
    ("participe passé", "过去分词"), ("participe présent", "现在分词"),
    ("subjonctif imparfait", "虚拟式未完成过去时"), ("imparfait du subjonctif", "虚拟式未完成过去时"),
    ("subjonctif", "虚拟式"), ("conditionnel", "条件式"), ("impératif", "命令式"),
    ("passé simple", "简单过去时"), ("futur", "简单将来时"), ("imparfait", "未完成过去时"),
    ("présent", "现在时"), ("féminin pluriel", "阴性复数"), ("masculin pluriel", "阳性复数"),
    ("féminin", "阴性"), ("pluriel", "复数"),
]


def normalize(word):
    """The word as typed: the typographic apostrophe of Wiktionary as '."""
    return word.replace("’", "'")


def fold(word):
    """The code of `word` (accents left out), or None."""
    out = []
    for ch in word.lower():
        out.append(FOLD.get(ch) or unicodedata.normalize("NFD", ch)[0])
    code = "".join(out).replace("-", "")
    return code if CODE.match(code) else None


def codes(word):
    """[(code, is_loose)]: the code, then the one without inner apostrophes."""
    code = fold(word)
    if code is None:
        return []
    result = [(code, False)]
    loose = code[:-1].replace("'", "") + code[-1]
    if loose != code:
        result.append((loose, True))
    return result


# ---- grammar ---------------------------------------------------------------

def elided(sense):
    """The word an elision sense is of (que for qu'), or None."""
    m = ELISION.match((sense.get("glosses") or [""])[0])
    return m.group(1) if m else None


def form_label(gloss):
    text = gloss.lower().replace("’", "'")
    for pattern, label in FORM_LABELS:
        if pattern in text:
            return label
    return "变形"


def first_form(forms, test):
    for f in forms:
        if test(set(f.get("tags", []))):
            return normalize(f.get("form", ""))
    return ""


def noun_grammar(word, entry):
    """"n.m. · 复数 chevaux", "n.f.", "n.m./n.f." ..."""
    tags = entry.get("tags", [])
    genders = [GENDERS[t] for t in ("masculine", "feminine") if t in tags]
    parts = ["/".join(genders)] if genders else []
    plural = first_form(entry.get("forms", []), lambda t: t == {"plural"})
    if plural and plural not in (word, word + "s"):
        parts.append("复数 " + plural)
    return " · ".join(parts)


def adj_grammar(word, entry):
    """"adj. · belle, beaux" when the feminine is not just word + e."""
    forms = entry.get("forms", [])
    feminine = first_form(forms, lambda t: {"singular", "feminine"} <= t)
    plural = first_form(forms, lambda t: {"plural", "masculine"} <= t)
    regular = feminine in ("", word, word + "e") and plural in ("", word, word + "s")
    if regular:
        return "adj."
    return "adj. · " + ", ".join(f for f in (feminine, plural) if f and f != word)


def grammar_of(word, entry):
    pos = entry.get("pos")
    if pos == "noun":
        return noun_grammar(word, entry)
    if pos == "adj":
        return adj_grammar(word, entry)
    return POS_LABELS.get(pos, "")


# ---- sources ---------------------------------------------------------------

def read_wiktionary(lines):
    """Return (translations, names, forms, lemmas, grammar) from wiktextract
    JSON lines of the French Wiktionary, like build_dewiktionary.read_wiktionary."""
    translations, names, forms, lemmas, grammar = {}, {}, {}, set(), {}
    for line in lines:
        entry = json.loads(line)
        if entry.get("lang_code") != "fr":
            continue
        word = normalize(entry.get("word", ""))
        if not FRENCH_WORD.match(word):
            continue
        senses = entry.get("senses", [])
        form_of = [s for s in senses if s.get("form_of") or elided(s)]
        if "form-of" not in entry.get("tags", []) and len(form_of) < len(senses):
            lemmas.add(word)
            if not grammar.get(word):  # the first entry that has any
                grammar[word] = grammar_of(word, entry)
        zh = [t["word"] for t in entry.get("translations", [])
              if t.get("lang_code") in CHINESE and HAN.match(t.get("word", ""))]
        if zh:
            table = names if entry.get("pos") == "name" else translations
            table.setdefault(word, []).extend(zh)
        for sense in form_of:
            gloss = (sense.get("glosses") or [""])[0]
            if elided(sense):
                targets, label = [elided(sense)], "省音形式"
            else:
                targets = [normalize(t.get("word", "")) for t in sense["form_of"]]
                label = form_label(gloss)
            for lemma in targets:
                if lemma and lemma != word:
                    forms.setdefault(word, []).append((lemma, label))
    for form in forms:
        forms[form] = list(dict(reversed(forms[form])).items())[::-1]  # first label per lemma
    for table in (translations, names):
        for key in table:
            table[key] = list(dict.fromkeys(table[key]))
    grammar = {w: g for w, g in grammar.items() if g}
    return translations, names, forms, lemmas, grammar


def clean_gloss(gloss):
    """The senses of a Chinese Wiktionary gloss, without the parts of speech."""
    if build_dewiktionary.PRONUNCIATION.search(gloss):
        return []
    gloss = PLURAL_NOTE.sub("", gloss.split("\n")[0])
    senses = []
    for part in POS_MARKS.split(gloss):
        # One printed-dictionary sense lists several: "马；骑术；马肉".
        for sense in part.split("；"):
            sense = build_dewiktionary.NOTES.sub("", sense).strip(" 。.;；:：")
            if HAS_HAN.search(sense) and "~" not in sense:
                senses.append(sense)
    return senses


def read_zh_wiktionary(lines):
    """{French word: [Chinese gloss of each sense]} from the Chinese Wiktionary."""
    glosses = {}
    for line in lines:
        if '"fr"' not in line:
            continue  # most lines are other languages; skip parsing them
        entry = json.loads(line)
        if entry.get("lang_code") != "fr":
            continue
        word = normalize(entry.get("word", ""))
        if not FRENCH_WORD.match(word):
            continue
        for sense in entry.get("senses", []):
            if {"form-of", "alt-of"} & set(sense.get("tags", [])):
                continue
            for gloss in sense.get("glosses", []):
                for part in clean_gloss(gloss):
                    glosses.setdefault(word, []).append(part)
    return {w: list(dict.fromkeys(g)) for w, g in glosses.items()}


def read_cfdict(lines, essay=None):
    """Return ({French word: [Chinese]}, {Traditional char: Simplified char})
    from CFDICT read backwards; ranked like build_dewiktionary.read_handedict."""
    essay = essay or {}
    found, t2s, simplified = {}, {}, set()
    for trad, simp, senses in build_handedict.parse(lines, build_cfdict.ENTRY, build_cfdict.clean):
        if len(trad) == 1 and len(simp) == 1:
            simplified.add(simp)
            if trad != simp:
                t2s.setdefault(trad, simp)
        if not HAN.match(simp):
            continue
        position = 0
        for sense in senses:
            if build_cfdict.PROPER_NAME.search(sense):
                continue
            for item in build_dewiktionary.split_items(sense):
                word = normalize(build_dewiktionary.PARENS.sub("", item).strip())
                if FRENCH_WORD.match(word):
                    rank = (-(essay.get(trad, 0) + 10) / (1 + position), len(simp))
                    best = found.setdefault(word, {})
                    if simp not in best or rank < best[simp]:
                        best[simp] = rank
                position += 1
    t2s = {t: s for t, s in t2s.items() if t not in simplified}
    return {w: sorted(c, key=c.get) for w, c in found.items()}, t2s


# ---- build -----------------------------------------------------------------

def build(translations, names, forms, lemmas, grammar, zh_glosses, cfdict, t2s, freq,
          with_forms=True):
    """Return ({word: gloss}, [(word, code, weight)]). Names and inflected
    forms are typeable when they are frequent or (forms) their lemma has Chinese."""
    chinese = {}
    for word in lemmas | forms.keys() | cfdict.keys() | zh_glosses.keys():
        zh = build_dewiktionary.chinese_of(word, translations, names, zh_glosses, cfdict, t2s)
        if zh:
            chinese[word] = zh
    vocabulary = {w for w in lemmas if w in chinese or w in grammar or w.lower() in freq}
    vocabulary |= set(chinese)
    if with_forms:
        vocabulary |= {f for f, pointers in forms.items()
                       if f.lower() in freq or any(lemma in chinese for lemma, _ in pointers)}
    # Maisons (a place) and ETE (an abbreviation) would come before the
    # completions of maison and été; german_case.lua capitalizes when needed.
    lowercase_codes = {fold(w) for w in vocabulary if w == w.lower()}
    vocabulary -= {w for w in vocabulary
                   if w != w.lower() and fold(w) in lowercase_codes and w not in chinese}

    glosses = {}
    for word in vocabulary:
        pointers = []
        for lemma, label in forms.get(word, []):
            if lemma in chinese and len(pointers) < 2:
                pointers.append("%s 的%s · %s" % (lemma, label, chinese[lemma][0]))
        if word in lemmas and (word in chinese or word in grammar):
            parts = [grammar.get(word, ""), "; ".join(chinese.get(word, []))]
            # été is a noun and a form of être: show both, the noun first.
            glosses[word] = " / ".join([" · ".join(p for p in parts if p)] + pointers[:1])
            continue
        if pointers:
            glosses[word] = " / ".join(pointers)
        elif word in chinese:
            glosses[word] = "; ".join(chinese[word])

    entries = []
    for word in vocabulary:
        # The frequency list has accents (où, ou): it ranks the right one first.
        # It is in lowercase: a capitalized word (Maison, a name) only gets the
        # frequency when there is no lowercase word (Paris).
        lower = word.lower()
        weight = freq.get(lower, 0) * 10 if word == lower or lower not in vocabulary else 0
        weight += 3 if word in chinese else (1 if word in lemmas else 0)
        weight += 1 if word in lemmas and word.islower() else 0
        for code, loose in codes(word):
            entries.append((word, code, weight * 9 // 10 if loose and weight > 9 else weight))
    entries.sort(key=lambda e: (e[1], -e[2], e[0]))
    return glosses, entries


DICT_HEADER = """%s
# Sources: French and Chinese Wiktionary via kaikki.org (CC BY-SA),
# CFDICT (CC BY-SA 3.0), FrequencyWords by Hermit Dave (CC BY-SA 4.0).
---
name: francais
version: "%s"
sort: by_weight
columns:
  - text
  - code
  - weight
...
"""


def write_outputs(out_dir, glosses, entries, version):
    os.makedirs(out_dir, exist_ok=True)
    dict_path = os.path.join(out_dir, "francais.dict.yaml")
    with open(dict_path, "w", encoding="utf-8", newline="\n") as out:
        out.write(DICT_HEADER % (MARKER, version))
        for word, code, weight in entries:
            out.write("%s\t%s\t%d\n" % (word, code, weight))
    tsv_path = os.path.join(out_dir, "fr_zh.tsv")
    with open(tsv_path, "w", encoding="utf-8", newline="\n") as out:
        out.write(MARKER + "\n")
        out.write("# French and Chinese Wiktionary via kaikki.org and CFDICT - licensed CC BY-SA\n")
        out.write("# sorted\n")  # unique keys in byte order: german_gloss.lua searches the file
        for word in sorted(glosses):
            out.write(word + "\t" + re.sub(r"[\t\r\n]+", " ", glosses[word]) + "\n")
    return dict_path, tsv_path


# ---- main ------------------------------------------------------------------

def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--source", help="French Wiktionary raw-wiktextract-data.jsonl[.gz]; default: download (~740 MB)")
    ap.add_argument("--zh-source", help="Chinese Wiktionary raw-wiktextract-data.jsonl[.gz]; default: download (~230 MB)")
    ap.add_argument("--cfdict", help="cfdict.u8; default: download")
    ap.add_argument("--frequency", help="fr_50k.txt; default: download")
    ap.add_argument("--essay", help="Rime essay.txt, ranks the Chinese of CFDICT")
    ap.add_argument("--output-dir", default=os.path.join(REPO, "french_input"))
    ap.add_argument("--no-forms", action="store_true",
                    help="leave out inflected forms that are not also a lemma")
    args = ap.parse_args(argv)

    download = build_dewiktionary.download
    with tempfile.TemporaryDirectory() as tmp:
        source = args.source or download(WIKTIONARY_URL, tmp, "fr-wiktextract.jsonl.gz")
        zh_source = args.zh_source or download(build_dewiktionary.ZH_WIKTIONARY_URL, tmp,
                                               "zh-wiktextract.jsonl.gz")
        cfdict = args.cfdict or download(build_cfdict.URL, tmp)
        frequency = args.frequency or download(FREQUENCY_URL, tmp)

        essay = {}
        if args.essay:
            with open(args.essay, encoding="utf-8") as fh:
                essay = build_dewiktionary.read_essay(fh)
        with open(cfdict, encoding="utf-8") as fh:
            reverse, t2s = read_cfdict(fh, essay)
        with open(frequency, encoding="utf-8") as fh:
            freq = build_dewiktionary.read_frequency(fh)
        print("reading " + source, file=sys.stderr)
        with build_dewiktionary.open_lines(source) as fh:
            translations, names, forms, lemmas, grammar = read_wiktionary(fh)
        print("reading " + zh_source, file=sys.stderr)
        with build_dewiktionary.open_lines(zh_source) as fh:
            zh_glosses = read_zh_wiktionary(fh)

    glosses, entries = build(translations, names, forms, lemmas, grammar, zh_glosses,
                             reverse, t2s, freq, with_forms=not args.no_forms)
    version = time.strftime("%Y.%m.%d")
    dict_path, tsv_path = write_outputs(args.output_dir, glosses, entries, version)
    print("wrote %d codes to %s" % (len(entries), dict_path), file=sys.stderr)
    print("wrote %d glosses to %s" % (len(glosses), tsv_path), file=sys.stderr)


if __name__ == "__main__":
    main()
