#!/usr/bin/env python3
"""Install TypeDuck's Cantonese schema (jyut6ping3) into Rime user directories.

TypeDuck's schema repository is written for TypeDuck's own librime fork and
frontends. This script installs it for stock librime with librime-lua:

1. Files: copies the schema, its dictionaries and its reverse-lookup helpers,
   but none of the files that would shadow the stock rime-data in the user
   directory (luna_pinyin, cangjie5, stroke, essay.txt, default.yaml). Those
   resolve to the shared data directory instead, so other schemas keep
   working. TypeDuck's essay.txt is installed as typeduck_essay.txt and the
   jyut6ping3 dictionary is pointed at it with `vocabulary:`.

2. Schema: drops `dictionary_lookup_filter` (only in TypeDuck's librime fork)
   and the \\f / \\v comment markers (only parsed by TypeDuck's frontends),
   turns on `spelling_hints` so every candidate shows its Jyutping with
   tones, and renames the catch-all recognizer pattern `reverse_lookup` so it
   no longer shadows the stroke lookup (`b). The files are edited directly: the schema starts with a root-level
   `__include`, and a jyut6ping3.custom.yaml is not applied to it.

3. Gloss: installs lua/typeduck_gloss.lua in place of the dropped filter and
   builds its index from jyut6ping3_scolar.dict.yaml, so candidates show
   TypeDuck's English (Hindi, Urdu, Nepali, Indonesian) definitions. A second
   index, built from jyut6ping3.dict.yaml, lists the pronunciations of every
   entry by frequency; the filter shows them on reverse-lookup candidates
   (`p Mandarin, `c Cangjie, ...), which would otherwise carry no Jyutping.

4. Reverse lookup (--flypy only): the schema's Mandarin lookup, prefix `p, is
   typed in full Pinyin. With --flypy it is typed in 小鶴雙拼 instead: the
   script installs jyut6ping3_flypy.schema.yaml, a helper schema that only
   compiles a Flypy prism for the luna_pinyin dictionary, and points the
   lookup at it. That also keeps the lookup independent of luna_pinyin.schema,
   whose prism is missing when a luna_pinyin.custom.yaml renames its dictionary.

The schema is not added to default.custom.yaml; the script prints the line to
add. Rerun after TypeDuck updates its schema. Redeploy Rime afterwards.
"""

import argparse
import csv
import filecmp
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parent
MARKER = "# generated by rime-german-gloss install-jyutping.py"
UPSTREAM = "https://github.com/TypeDuck-HK/schema.git"
SCHEMA = "jyut6ping3"
FILTER = "lua_filter@*typeduck_gloss"
ESSAY = "typeduck_essay"
INDEX = "lua/typeduck_gloss.txt"
READINGS = "lua/typeduck_readings.txt"
FLYPY = SCHEMA + "_flypy"
# New name of the schema's catch-all recognizer pattern "reverse_lookup"; see
# patch_schema().
LOOKUP_TAG = "zz_reverse_lookup"

# Copied unchanged. Everything else in the source is either generated below,
# mobile-only, or would shadow a stock file of the same name.
VERBATIM = [
    "include.yaml",
    "common.yaml",
    "common.custom.yaml",
    "jyut6ping3_scolar.schema.yaml",
    "jyut6ping3_scolar.dict.yaml",
    "loengfan.schema.yaml",
    "loengfan.dict.yaml",
    "cangjie3.schema.yaml",
    "cangjie3.dict.yaml",
    "quick3.schema.yaml",
    "quick3.dict.yaml",
    "quick5.schema.yaml",
    "quick5.dict.yaml",
]
# Reverse-lookup dictionaries the schema uses but this script leaves to rime-data.
STOCK = ["luna_pinyin", "stroke", "cangjie5"]

# Columns of the comma-separated first field of jyut6ping3_scolar.dict.yaml,
# after TypeDuck-Web src/CandidateInfo.ts (which reads the same rows with
# column 7, the pronunciation rank, removed).
COL_JYUTPING, COL_POS = 0, 10
COL_GLOSSES = [16, 17, 18, 19, 20]  # eng, hin, urd, nep, ind
LANGUAGES = ["eng", "hin", "urd", "nep", "ind"]
US, RS = "\x1f", "\x1e"


# ---- text transformations --------------------------------------------------

def marker_line(text, char):
    r"""Match a list item `- xform/^/\<char>/`, quoted or not."""
    return re.match(r"""^\s*-\s*['"]?xform/\^/\\%s/['"]?\s*$""" % char, text) is not None


def patch_template(text, languages, spelling_hints):
    """Adapt template.yaml to stock librime; see the module docstring."""
    lines = text.split("\n")
    out, swapped, hinted = [], False, False
    for line in lines:
        if line.strip() == "- dictionary_lookup_filter":
            out.append(line.replace("dictionary_lookup_filter", FILTER))
            swapped = True
        elif marker_line(line, "f"):
            continue
        else:
            out.append(line)
            if line.rstrip() == "translator:" and spelling_hints > 0:
                out.append("  spelling_hints: %d" % spelling_hints)
                hinted = True
    if not swapped:
        raise ValueError("template.yaml: no '- dictionary_lookup_filter' in engine/filters")
    if spelling_hints > 0 and not hinted:
        raise ValueError("template.yaml: no top-level 'translator:' section")
    while out and out[-1] == "":
        out.pop()
    out += [
        "",
        "typeduck_gloss:",
        "  languages: [ %s ]" % ", ".join(languages),
        "  show_pos: true",
        '  separator: " / "',
        "  max_length: 60",
        "",
    ]
    return "\n".join(out)


def patch_schema(text):
    r"""Adapt jyut6ping3.schema.yaml to stock librime and other frontends.

    Removes the \v comment markers; a `comment_format:` left without items is
    removed with them.

    Renames the catch-all recognizer pattern `reverse_lookup` ("`" followed by
    anything) to LOOKUP_TAG. librime tries the patterns in the order of their
    names and takes the first that matches, so the catch-all shadows every
    lookup named after it: "`b..." was tagged reverse_lookup instead of stroke
    and the stroke lookup never produced a candidate. The new name sorts last.
    """
    lines = [line for line in text.split("\n") if not marker_line(line, "v")]
    out, section = [], None
    tagged = pattern = False
    for i, line in enumerate(lines):
        if line and not line[0].isspace() and not line.startswith("#"):
            section = line.split(":")[0]
        if line.strip() == "comment_format:":
            rest = [l for l in lines[i + 1:] if l.strip()]
            if not rest or not rest[0].lstrip().startswith("- "):
                continue
        if section == "reverse_lookup" and line.strip() == "tag: reverse_lookup":
            line = line.replace("reverse_lookup", LOOKUP_TAG)
            tagged = True
        elif section == "recognizer" and line.strip().startswith("reverse_lookup:"):
            line = line.replace("reverse_lookup", LOOKUP_TAG, 1)
            pattern = True
        out.append(line)
    if not tagged:
        raise ValueError("jyut6ping3.schema.yaml: no 'tag: reverse_lookup' in the reverse_lookup section")
    if not pattern:
        raise ValueError("jyut6ping3.schema.yaml: no 'reverse_lookup' pattern in recognizer/patterns")
    return "\n".join(out)


def patch_flypy(text):
    """Make the Mandarin reverse lookup of jyut6ping3.schema.yaml take 小鶴雙拼.

    The FLYPY schema replaces luna_pinyin as a dependency and provides the
    prism; the Pinyin `preedit_format:` goes, as it would rewrite the codes.
    """
    out, section, skipping = [], None, False
    depends = prism = False
    for line in text.split("\n"):
        if line and not line[0].isspace() and not line.startswith("#"):
            section = line.split(":")[0]
        if skipping:
            if line.lstrip().startswith("- "):
                continue
            skipping = False
        if section == "schema" and line.strip() == "- luna_pinyin":
            line = line.replace("luna_pinyin", FLYPY)
            depends = True
        elif section == "luna_pinyin":
            key = line.strip().split(":")[0]
            if key == "preedit_format":
                skipping = True
                continue
            if key == "tips":
                line = line.split(":")[0] + ": 〔普通話·小鶴〕"
            elif key == "dictionary":
                out.append(line)
                line = line.split("dictionary:")[0] + "prism: " + FLYPY
                prism = True
        out.append(line)
    if not depends:
        raise ValueError("jyut6ping3.schema.yaml: no '- luna_pinyin' in schema/dependencies")
    if not prism:
        raise ValueError("jyut6ping3.schema.yaml: no 'dictionary:' in the luna_pinyin section")
    return "\n".join(out)


